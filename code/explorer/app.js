async function loadAblations() {
  const list = document.getElementById("ablation-list");
  const detail = document.getElementById("ablation-detail");
  // Reading every campaign's cells off disk takes a moment, so say so rather
  // than leaving the panel blank and looking broken.
  list.innerHTML = `<div class="loading"><span class="spinner"></span>Reading ablations…</div>`;
  if (detail) detail.innerHTML = `<div class="loading"><span class="spinner"></span>Reading ablations…</div>`;
  try {
    const resp = await fetch("/api/ablations");
    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
    ablationData = await resp.json();
    renderAblationList();
  } catch (e) {
    list.innerHTML =
      `<div class="empty-state" style="font-size:13px;padding:1rem;">Failed to load ablations: ${esc(e.message)}</div>`;
    if (detail) detail.innerHTML = "";
  }
}

function renderAblationList() {
  if (!ablationData) return;
  const kind = document.getElementById("ablation-kind").value;
  const items = ablationData.ablations.filter(a => !kind || a.kind === kind);
  document.getElementById("ablation-count").textContent =
    `${items.length} of ${ablationData.ablations.length}`;
  document.getElementById("ablation-list").innerHTML = items.map(a => `
    <button class="ablation-card${a.key === ablationSelected ? " active" : ""}"
            data-key="${a.key}">
      <span class="ablation-kind kind-${a.kind.replace(/[^a-z]/g, "")}">${a.kind}</span>
      <span class="ablation-title">${esc(a.title)}</span>
      <span class="ablation-meta">${a.runs.length
          ? `${a.runs.length} run${a.runs.length === 1 ? "" : "s"}`
          : "no runs of its own"} &middot; ${a.tables.length} table${a.tables.length === 1 ? "" : "s"}</span>
    </button>`).join("");
  document.querySelectorAll("#ablation-list .ablation-card").forEach(card => {
    card.addEventListener("click", () => selectAblation(card.dataset.key));
  });
  if (!ablationSelected && items.length) selectAblation(items[0].key);
}

function selectAblation(key) {
  ablationSelected = key;
  const a = ablationData.ablations.find(x => x.key === key);
  if (!a) return;
  document.querySelectorAll("#ablation-list .ablation-card").forEach(c =>
    c.classList.toggle("active", c.dataset.key === key));

  document.getElementById("ablation-detail").innerHTML = `
    <div class="ablation-detail-head">
      <span class="ablation-kind kind-${a.kind.replace(/[^a-z]/g, "")}">${a.kind}</span>
      <h3>${esc(a.title)}</h3>
      ${a.paper_ref ? `<span class="ablation-ref">${esc(a.paper_ref)}</span>` : ""}
    </div>
    ${a.concern ? `<p class="ablation-concern">${esc(a.concern)}</p>` : ""}
    ${renderAblationRuns(a)}
    ${renderAblationResults(a)}
    <h4>Files</h4>
    <ul class="ablation-ul">${a.tables.length
      ? a.tables.map(f => `<li>
          <button class="link-btn" data-table="${esc(f.path)}">${esc(f.name)}</button>
          <span class="dim">${(f.bytes / 1024).toFixed(1)} KB</span></li>`).join("")
      : `<li class="dim">No derived tables.</li>`}</ul>
    <div id="ablation-table-view"></div>`;

  document.querySelectorAll("#ablation-detail [data-table]").forEach(b => {
    b.addEventListener("click", () => showAblationTable(b.dataset.table));
  });
  document.querySelectorAll("#ablation-detail [data-open-run]").forEach(b => {
    b.addEventListener("click", () => openRunInEvaluator(b.dataset.openRun));
  });
}

async function showAblationTable(path) {
  const host = document.getElementById("ablation-table-view");
  host.innerHTML = `<div class="loading"><span class="spinner"></span>Loading ${esc(path)}…</div>`;
  try {
    const resp = await fetch(`/api/ablations/table?path=${encodeURIComponent(path)}`);
    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
    const d = await resp.json();
    const markdown = d.name.endsWith(".md");
    host.innerHTML = `
      <h4>${esc(d.name)}</h4>
      ${markdown
        ? `<div class="ablation-results">${renderMarkdown(d.text)}</div>`
        : `<pre class="ablation-table">${esc(d.text)}</pre>`}`;
  } catch (e) {
    host.innerHTML = `<div class="empty-state">Could not read ${esc(path)}: ${esc(e.message)}</div>`;
  }
}

function renderAblationRuns(a) {
  if (!a.runs.length) {
    return `<h4>Runs</h4>
      <p class="ablation-none">No runs of its own — this re-analyses the main
      study run under a different definition or aggregation.</p>`;
  }
  const root = a.run_root ? `<span class="dim">${esc(a.run_root)}/</span>` : "";
  const head = a.kind === "campaign"
    ? `<tr><th>Pass</th><th>Grid</th><th class="num">Planned</th>
         <th class="num">On disk</th><th class="num">Timeout</th><th></th></tr>`
    : `<tr><th>Run</th><th>Models</th><th class="num">Records</th><th></th></tr>`;

  const rows = a.runs.map(r => {
    if (a.kind === "campaign") {
      const short = r.role === "completion pass" ? "completion" : "generation";
      return `<tr>
        <td><code>${esc(r.name)}</code>
            <span class="pill pill-${short}">${esc(short)}</span></td>
        <td class="grid-cell">
          ${r.models.map(m => `<span class="chip">${esc(m)}</span>`).join("")}
          ${r.conditions.map(c => `<span class="chip chip-alt">${esc(c)}</span>`).join("")}
          <span class="dim">${r.scenarios} scenarios</span>
        </td>
        <td class="num">${r.planned.toLocaleString()}</td>
        <td class="num">${r.on_disk.toLocaleString()}</td>
        <td class="num">${r.timeout ? r.timeout + "s" : "—"}</td>
        <td><button class="link-btn" data-open-run="${esc("ablations/" + r.run_id)}">open</button></td></tr>`;
    }
    return `<tr>
      <td><code>${esc(r.run_id)}</code> <span class="pill">${esc(r.kind)}</span></td>
      <td class="grid-cell">${r.models.map(m => `<span class="chip">${esc(m)}</span>`).join("")}</td>
      <td class="num">${(r.records || 0).toLocaleString()}</td>
      <td><button class="link-btn" data-open-run="${esc(r.run_id)}">open</button></td></tr>`;
  }).join("");

  return `<h4>Runs ${root}</h4>
    ${renderCoverage(a)}
    <div class="ablation-table-wrap">
      <table class="ablation-runs">${head}${rows}</table>
    </div>`;
}

// Completeness is a property of the ablation, not of any one pass. A pass that
// timed out on some cells was finished by a later one; both halves are kept
// because each holds cells the other does not.
function renderCoverage(a) {
  const c = a.coverage;
  if (!c) return "";
  const passes = a.runs.length;
  const extra = c.extra
    ? ` <span class="dim">+${c.extra.toLocaleString()} attempts carried over from an earlier plan</span>`
    : "";
  if (c.complete) {
    return `<p class="coverage coverage-ok">
      <strong>Complete.</strong> All ${c.expected.toLocaleString()} planned cells
      are present, across ${passes} pass${passes === 1 ? "" : "es"}.${extra}</p>`;
  }
  return `<p class="coverage coverage-gap">
    <strong>${c.missing.toLocaleString()} cells missing.</strong>
    ${c.covered.toLocaleString()} of ${c.expected.toLocaleString()} planned cells
    are present.${extra}</p>`;
}

function renderAblationResults(a) {
  if (!a.results) return `<h4>Results</h4><p class="ablation-none">No result write-up.</p>`;
  // renderMarkdown is the app's own renderer, shared with the results summary.
  return `<h4>Results <span class="dim">${esc(a.results.path)}</span></h4>
    <div class="ablation-results">${renderMarkdown(a.results.markdown)}</div>`;
}

async function openRunInEvaluator(runId) {
  const tab = document.querySelector('.app-tabs .tab[data-view="evaluator-view"]');
  if (tab) tab.click();

  // sel-run is a custom checkbox multi-select, not a <select>. It is built from
  // the run manifest, which may still be in flight when the button is clicked —
  // so wait for the option to exist instead of failing silently.
  const option = async () => {
    for (let wait = 0; wait < 40; wait++) {
      const box = document.querySelector(
        `#sel-run .ms-option input[value="${CSS.escape(runId)}"]`);
      if (box) return box;
      await new Promise(r => setTimeout(r, 250));
    }
    return null;
  };
  const target = await option();
  if (!target) {
    alert(`Run "${runId}" is not in the run list.`);
    return;
  }
  document.querySelectorAll("#sel-run .ms-option input").forEach(cb => {
    cb.checked = cb === target;
  });
  onMultiSelectChange("sel-run");
}


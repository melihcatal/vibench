async function fetchResults(reset) {
  if (reset) { currentOffset = 0; filteredResults = []; }

  const selModels = getMultiSelectValues("sel-model");
  const hasAll = selModels.includes("__all__");
  const modelIds = selModels.filter(v => v !== "__all__");

  if (!hasAll && modelIds.length === 0) {
    currentModelResults = []; filteredResults = []; currentIdx = -1; totalResults = 0;
    renderResultList(); showEmptyDetail("Select a model to begin evaluation"); return;
  }

  const selModalities = getMultiSelectValues("sel-modality");
  const selScenarios = getMultiSelectValues("sel-scenario");
  const selSubtasks = getMultiSelectValues("sel-subtask");
  const filter = document.getElementById("sel-filter").value;
  const selRuns = getSelectedRuns();

  if (reset) showEmptyDetail("Loading...");
  isLoadingMore = true;

  const params = new URLSearchParams();
  params.set("model", hasAll ? "__all__" : modelIds.join(","));
  if (selRuns.length > 0 && runsManifest && selRuns.length < runsManifest.runs.length) {
    params.set("run", selRuns.join(","));
  }
  if (selModalities.length > 0 && selModalities.length < 4) params.set("modality", selModalities.join(","));
  const totalScenarios = benchmarkData ? benchmarkData.scenarios.length : 20;
  if (selScenarios.length > 0 && selScenarios.length < totalScenarios) params.set("scenario", selScenarios.join(","));
  if (selSubtasks.length > 0 && selSubtasks.length < 4) params.set("subtask", selSubtasks.join(","));
  if (filter && filter !== "all") params.set("filter", filter);
  params.set("offset", currentOffset);
  params.set("limit", PAGE_SIZE);

  try {
    const resp = await fetch(`/api/results?${params}`);
    if (!resp.ok) throw new Error(`HTTP ${resp.status}`);
    const data = await resp.json();
    totalResults = data.total;

    if (reset) {
      filteredResults = data.results;
    } else {
      filteredResults = filteredResults.concat(data.results);
    }

    // Client-side filters that need evaluation state (can't do server-side)
    let displayResults = filteredResults;
    if (filter === "unevaluated") {
      displayResults = filteredResults.filter(r => !evaluations[evalKey(r)]);
    } else if (filter === "flagged") {
      displayResults = filteredResults.filter(r => { const ev = evaluations[evalKey(r)]; return ev && ev.correct === "no"; });
    }

    // Client-side sort
    const confOrder = { high: 0, medium: 1, low: 2, none: 3, "": 4 };
    if (sortField === "scenario") displayResults.sort((a, b) => a.scenario_id.localeCompare(b.scenario_id) || a.task_id.localeCompare(b.task_id));
    else if (sortField === "confidence") displayResults.sort((a, b) => (confOrder[a.detection_confidence] || 4) - (confOrder[b.detection_confidence] || 4));
    else if (sortField === "ecosystem") displayResults.sort((a, b) => (a.detected_ecosystem || "zzz").localeCompare(b.detected_ecosystem || "zzz"));
    else if (sortField === "modality") displayResults.sort((a, b) => a.modality.localeCompare(b.modality) || a.scenario_id.localeCompare(b.scenario_id));

    // Use displayResults for rendering
    filteredResults = displayResults;

    renderResultList();
    if (reset && filteredResults.length > 0) selectResult(0);
    else if (reset) { currentIdx = -1; showEmptyDetail(totalResults === 0 ? "No results match filters." : "No results."); }
    updateProgress();
  } catch (e) {
    console.error(e);
    if (reset) showEmptyDetail(`Failed: ${e.message}`);
  }
  isLoadingMore = false;
}


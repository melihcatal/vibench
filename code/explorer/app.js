function evalKey(r) {
  return [
    r.run_id || "",
    r.model_id || "",
    r.modality || "",
    r.task_id || "",
    r.sub_requirement_id || "",
    r.session_dir || "",
    `c${r.completion_index}`,
  ].join("__");
}

function loadEvalIntoForm(ev) {
  document.querySelectorAll('input[name="eval-correct"]').forEach(r => { r.checked = false; });
  document.getElementById("correction-fields").classList.remove("show");
  document.getElementById("corr-provider").value = "";
  document.getElementById("corr-ecosystem").value = "";
  document.getElementById("corr-service").value = "";
  document.getElementById("eval-notes").value = "";
  if (ev) {
    if (ev.correct) {
      const radio = document.querySelector(`input[name="eval-correct"][value="${ev.correct}"]`);
      if (radio) radio.checked = true;
      if (ev.correct === "no") {
        document.getElementById("correction-fields").classList.add("show");
        document.getElementById("corr-provider").value = ev.correct_provider || "";
        document.getElementById("corr-ecosystem").value = ev.correct_ecosystem || "";
        document.getElementById("corr-service").value = ev.correct_service || "";
      }
    }
    document.getElementById("eval-notes").value = ev.notes || "";
  }
}

function saveCurrentEvaluation() {
  if (currentIdx < 0 || currentIdx >= filteredResults.length) return;
  const r = filteredResults[currentIdx];
  const key = evalKey(r);
  const correctVal = document.querySelector('input[name="eval-correct"]:checked')?.value || "";
  const ev = {
    run_id: r.run_id, model_id: r.model_id, task_id: r.task_id, completion_index: r.completion_index,
    modality: r.modality, scenario_id: r.scenario_id,
    sub_requirement_id: r.sub_requirement_id || "", session_dir: r.session_dir || "",
    detected_provider: r.detected_provider, detected_ecosystem: r.detected_ecosystem,
    correct: correctVal,
    correct_provider: correctVal === "no" ? document.getElementById("corr-provider").value : "",
    correct_ecosystem: correctVal === "no" ? document.getElementById("corr-ecosystem").value : "",
    correct_service: correctVal === "no" ? document.getElementById("corr-service").value : "",
    notes: document.getElementById("eval-notes").value,
    timestamp: new Date().toISOString(),
  };
  if (!correctVal) delete evaluations[key]; else evaluations[key] = ev;
  saveEvaluationsToStorage();
  saveEvalToServer(key, correctVal ? ev : null);
  document.getElementById("save-status").textContent = "Saved";
  setTimeout(() => { const el = document.getElementById("save-status"); if (el) el.textContent = ""; }, 2000);
  const listItem = document.querySelector(`.eval-result-item[data-idx="${currentIdx}"]`);
  if (listItem) {
    const dot = listItem.querySelector(".ri-eval-dot");
    if (dot) dot.className = `ri-eval-dot ${correctVal === "yes" ? "yes" : correctVal === "no" ? "no" : "none"}`;
  }
  updateProgress();
}

// ── Persistence ──────────────────────────────────────────────

async function saveEvaluationsToStorage() {
  try { localStorage.setItem(STORAGE_KEY, JSON.stringify(evaluations)); } catch (e) { /* */ }
}
async function loadEvaluationsFromStorage() {
  try { const resp = await fetch("/api/evaluations"); if (resp.ok) { evaluations = await resp.json(); return; } } catch (e) { /* */ }
  try { const raw = localStorage.getItem(STORAGE_KEY); if (raw) evaluations = JSON.parse(raw); } catch (e) { evaluations = {}; }
}
async function saveEvalToServer(key, ev) {
  try { await fetch("/api/evaluations", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ key, evaluation: ev || {} }) }); } catch (e) { /* */ }
}
function downloadEvaluations() {
  const arr = Object.values(evaluations);
  if (!arr.length) { alert("No evaluations."); return; }
  const blob = new Blob([JSON.stringify(arr, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a"); a.href = url; a.download = `vibench_evaluations_${new Date().toISOString().slice(0,10)}.json`;
  document.body.appendChild(a); a.click(); document.body.removeChild(a); URL.revokeObjectURL(url);
}
function uploadEvaluations(e) {
  const file = e.target.files[0]; if (!file) return;
  const reader = new FileReader();
  reader.onload = async function(evt) {
    try {
      const arr = JSON.parse(evt.target.result);
      if (!Array.isArray(arr)) throw new Error("Expected array");
      let n = 0;
      arr.forEach(ev => { if (ev.model_id && ev.task_id && ev.correct) { evaluations[`${ev.model_id}__${ev.task_id}__c${ev.completion_index}`] = ev; n++; } });
      saveEvaluationsToStorage();
      try { await fetch("/api/evaluations/bulk", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(arr) }); } catch(err) { /* */ }
      alert(`Imported ${n} evaluations.`);
      if (filteredResults.length > 0) { renderResultList(); if (currentIdx >= 0) selectResult(currentIdx); updateProgress(); }
    } catch(err) { alert("Failed: " + err.message); }
  };
  reader.readAsText(file); e.target.value = "";
}

function esc(s) {
  if (s == null) return "";
  return String(s).replace(/&/g,"&amp;").replace(/</g,"&lt;").replace(/>/g,"&gt;").replace(/"/g,"&quot;").replace(/'/g,"&#039;");
}

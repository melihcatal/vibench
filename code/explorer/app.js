// The order files were produced in is what the cascade claim is about: an
// anchor read first, then the files that follow it. Shown as a sequence, and
// labelled when the order is inferred from one response rather than recorded.
function renderGenerationOrder(order) {
  if (!order || !order.events || !order.events.length) return "";
  const rows = order.events.map(e => `
    <tr>
      <td class="num">${e.step != null ? `step ${e.step}` : e.n}</td>
      <td><span class="pill">${esc(e.tool || "")}</span></td>
      <td><code>${esc(e.file || "")}</code></td>
      <td><span class="dim">${esc(e.role || "—")}</span></td>
      <td>${e.ecosystem
          ? `<span class="eco eco-${esc(e.ecosystem)}">${esc(e.ecosystem)}</span>`
          : `<span class="dim">undetected</span>`}</td>
    </tr>`).join("");
  return `<div class="card" style="padding:.9rem 1rem;">
    <h4 style="margin:0 0 .4rem;">Generation order
      <span class="pill ${order.observed ? "pill-ok" : "pill-warn"}">
        ${order.observed ? "recorded" : "inferred"}</span>
      <span class="dim">${esc(order.source || "")}</span></h4>
    <p class="ablation-none" style="margin:0 0 .6rem;">${esc(order.note || "")}</p>
    <div class="ablation-table-wrap"><table class="ablation-runs">
      <tr><th class="num">#</th><th>Action</th><th>File</th><th>Role</th><th>Ecosystem</th></tr>
      ${rows}
    </table></div>
  </div>`;
}

function renderAgenticFiles(r, detail) {
  const section = document.getElementById("agentic-files-section");
  const files = detail.agentic_files || {};
  const components = detail.agentic_components || {};
  const metrics = detail.agentic_metrics || {};
  let html = renderGenerationOrder(detail.generation_order);

  // Session metrics (clickable for description)
  if (Object.keys(metrics).length) {
    html += `<div class="card detection-card"><div class="detection-grid">`;
    for (const [k, v] of Object.entries(metrics)) {
      const val = typeof v === "number" ? v.toFixed(2) : String(v);
      const hasInfo = METRIC_INFO[k];
      html += `<div class="det-item ${hasInfo ? "metric-clickable" : ""}" ${hasInfo ? `data-metric="${esc(k)}"` : ""}>
        <div class="det-label">${esc(k.replace(/_/g, " "))}${hasInfo ? ' <span class="material-icons-outlined" style="font-size:12px;vertical-align:middle;">info</span>' : ""}</div>
        <div class="det-value">${esc(val)}</div>
      </div>`;
    }
    html += `</div></div>`;
  }

  // Each file with per-file eval
  const fileNames = Object.keys(files);
  if (!fileNames.length) {
    html += `<div class="card" style="padding:1rem;"><p class="text-muted">No generated files.</p></div>`;
  } else {
    fileNames.forEach(fname => {
      const comp = components[fname.replace(/\.py$/, "")] || {};
      const eco = comp.ecosystem || "";
      const group = comp.coupling_expectation || comp.component_group || "";
      const fileKey = `${r.run_id || ""}__${r.model_id}__${r.task_id}__${r.session_dir || ""}__c${r.completion_index}__${fname}`;
      const fileEval = evaluations[fileKey];
      const evalDot = fileEval ? (fileEval.correct === "yes" ? "yes" : "no") : "none";

      html += `<div class="card">
        <div class="card-header" style="gap:0.5rem;flex-wrap:wrap;">
          <div class="ri-eval-dot ${evalDot}" style="width:10px;height:10px;"></div>
          <span class="material-icons-outlined" style="font-size:18px;">insert_drive_file</span>
          <span class="mono" style="font-weight:700;">${esc(fname)}</span>
          ${eco ? `<span class="badge badge-eco-${esc(eco)}" style="font-size:10px;">${esc(eco)}</span>` : ""}
          ${group ? `<span class="comp-group ${esc(group)}" style="font-size:9px;">${esc(group.replace(/_/g, " "))}</span>` : ""}
          ${comp.service ? `<span class="text-muted text-sm">${esc(comp.service)}</span>` : ""}
          ${comp.confidence ? `<span class="badge badge-conf-${esc(comp.confidence)}" style="font-size:9px;">${esc(comp.confidence)}</span>` : ""}
          <div style="margin-left:auto;display:flex;gap:0.3rem;">
            <button class="btn-icon btn-icon-sm file-eval-btn" data-file-key="${esc(fileKey)}" data-val="yes" title="Correct" style="${fileEval?.correct==='yes'?'color:var(--success);border-color:var(--success);':''}"><span class="material-icons-outlined">check</span></button>
            <button class="btn-icon btn-icon-sm file-eval-btn" data-file-key="${esc(fileKey)}" data-val="no" title="Incorrect" style="${fileEval?.correct==='no'?'color:var(--error);border-color:var(--error);':''}"><span class="material-icons-outlined">close</span></button>
          </div>
        </div>
        <pre class="code-block code-dark">${esc(files[fname])}</pre>
      </div>`;
    });
  }

  section.innerHTML = html;

  // Metric click handlers (popup)
  section.querySelectorAll(".metric-clickable").forEach(el => {
    el.addEventListener("click", () => {
      const key = el.dataset.metric;
      const info = METRIC_INFO[key];
      if (!info) return;
      showMetricPopup(info, el);
    });
  });

  // Attach per-file eval handlers
  section.querySelectorAll(".file-eval-btn").forEach(btn => {
    btn.addEventListener("click", () => {
      const fk = btn.dataset.fileKey;
      const val = btn.dataset.val;
      const existing = evaluations[fk];
      if (existing && existing.correct === val) {
        delete evaluations[fk]; // toggle off
      } else {
        evaluations[fk] = { correct: val, timestamp: new Date().toISOString() };
      }
      saveEvaluationsToStorage();
      saveEvalToServer(fk, evaluations[fk] || null);
      // Re-render to update dots/buttons
      renderAgenticFiles(r, detail);
    });
  });
}

function showMetricPopup(info, anchor) {
  // Remove any existing popup
  document.querySelectorAll(".metric-popup").forEach(p => p.remove());
  const popup = document.createElement("div");
  popup.className = "metric-popup";
  popup.innerHTML = `
    <div class="metric-popup-header">
      <strong>${esc(info.title)}</strong>
      <button class="metric-popup-close">&times;</button>
    </div>
    <p>${esc(info.desc)}</p>
    <div class="metric-popup-example"><strong>Example:</strong> ${esc(info.example)}</div>`;
  document.body.appendChild(popup);

  // Position near the anchor
  const rect = anchor.getBoundingClientRect();
  popup.style.top = (rect.bottom + 8) + "px";
  popup.style.left = Math.max(8, Math.min(rect.left, window.innerWidth - 360)) + "px";

  popup.querySelector(".metric-popup-close").addEventListener("click", () => popup.remove());
  // Close on outside click
  setTimeout(() => {
    const closer = (e) => { if (!popup.contains(e.target) && !anchor.contains(e.target)) { popup.remove(); document.removeEventListener("click", closer); } };
    document.addEventListener("click", closer);
  }, 10);
}


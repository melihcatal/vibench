function categorizeRuns(runs) {
  // Group runs into a stable, semantic order so the dropdown reads top-down
  // from "most canonical" to "most ablation-y".
  const groups = [
    { label: "Direct — Complete",                   prefix: "direct/complete/" },
    { label: "Agentic — Complete",                  prefix: "agentic/complete/" },
    { label: "Direct — Option order",               prefix: "direct/variants/option_order/" },
    { label: "Agentic — Option order (OpenCode)",   prefix: "agentic/variants/option_order/opencode/" },
    { label: "Agentic — Option order (Agents SDK)", prefix: "agentic/variants/option_order/agents_sdk/" },
    { label: "Campaign — Initial provider",         prefix: "ablations/initial_provider/" },
    { label: "Campaign — Agentic mechanism",        prefix: "ablations/agentic_mechanism/" },
  ];
  const buckets = groups.map(g => ({ label: g.label, items: [] }));
  const other = { label: "Other", items: [] };
  for (const run of runs) {
    const id = run.run_id;
    let placed = false;
    for (let i = 0; i < groups.length; i++) {
      if (id.startsWith(groups[i].prefix)) {
        buckets[i].items.push({
          value: id,
          shortLabel: id.slice(groups[i].prefix.length),
          fullLabel: id,
          selected: false,
        });
        placed = true;
        break;
      }
    }
    if (!placed) other.items.push({ value: id, shortLabel: id, fullLabel: id, selected: false });
  }
  if (other.items.length) buckets.push(other);
  return buckets.filter(b => b.items.length > 0);
}


function initMultiSelect(containerId, options) {
  const container = document.getElementById(containerId);
  const placeholder = container.dataset.placeholder || "Select...";

  // Build DOM
  const trigger = document.createElement("div");
  trigger.className = "ms-trigger";
  trigger.innerHTML = `<span class="ms-label">${placeholder}</span><span class="material-icons-outlined ms-arrow">expand_more</span>`;

  const dropdown = document.createElement("div");
  dropdown.className = "ms-dropdown";

  options.forEach(opt => {
    const row = document.createElement("div");
    row.className = "ms-option";
    const cb = document.createElement("input");
    cb.type = "checkbox";
    cb.value = opt.value;
    cb.checked = !!opt.selected;
    cb.id = `ms-${containerId}-${opt.value}`;
    const lbl = document.createElement("label");
    lbl.htmlFor = cb.id;
    lbl.textContent = opt.label;
    lbl.title = opt.label;
    row.title = opt.label;
    row.appendChild(cb);
    row.appendChild(lbl);
    row.addEventListener("click", (e) => {
      if (e.target !== cb) cb.checked = !cb.checked;
      onMultiSelectChange(containerId);
    });
    dropdown.appendChild(row);
  });

  container.innerHTML = "";
  container.appendChild(trigger);
  container.appendChild(dropdown);

  // Toggle dropdown
  trigger.addEventListener("click", (e) => {
    e.stopPropagation();
    const isOpen = dropdown.classList.contains("open");
    closeAllMultiSelects();
    if (!isOpen) {
      dropdown.classList.add("open");
      trigger.classList.add("open");
    }
  });

  updateMultiSelectLabel(containerId);
}

function closeAllMultiSelects() {
  document.querySelectorAll(".ms-dropdown.open").forEach(d => d.classList.remove("open"));
  document.querySelectorAll(".ms-trigger.open").forEach(t => t.classList.remove("open"));
}

function initGroupedMultiSelect(containerId, groups) {
  // groups: [{label, items: [{value, shortLabel, fullLabel, selected}, ...]}, ...]
  const container = document.getElementById(containerId);
  const placeholder = container.dataset.placeholder || "Select...";

  const trigger = document.createElement("div");
  trigger.className = "ms-trigger";
  trigger.innerHTML = `<span class="ms-label">${placeholder}</span><span class="material-icons-outlined ms-arrow">expand_more</span>`;

  const dropdown = document.createElement("div");
  dropdown.className = "ms-dropdown";

  groups.forEach((group, gIdx) => {
    const header = document.createElement("div");
    header.className = "ms-group-header";
    header.innerHTML = `
      <span class="ms-group-label">${group.label}</span>
      <span class="ms-group-toggle" data-group-index="${gIdx}" title="Select / clear all in this group">all</span>
    `;
    dropdown.appendChild(header);

    group.items.forEach(opt => {
      const row = document.createElement("div");
      row.className = "ms-option ms-option-grouped";
      const cb = document.createElement("input");
      cb.type = "checkbox";
      cb.value = opt.value;
      cb.checked = !!opt.selected;
      cb.id = `ms-${containerId}-${opt.value.replace(/[^a-zA-Z0-9_-]/g, "_")}`;
      cb.dataset.groupIndex = String(gIdx);
      const lbl = document.createElement("label");
      lbl.htmlFor = cb.id;
      lbl.textContent = opt.shortLabel;
      lbl.title = opt.fullLabel;
      row.title = opt.fullLabel;
      row.appendChild(cb);
      row.appendChild(lbl);
      row.addEventListener("click", (e) => {
        if (e.target !== cb) cb.checked = !cb.checked;
        onMultiSelectChange(containerId);
      });
      dropdown.appendChild(row);
    });
  });

  // Group "select all / clear all" toggles.
  dropdown.querySelectorAll(".ms-group-toggle").forEach(toggle => {
    toggle.addEventListener("click", (e) => {
      e.stopPropagation();
      const gIdx = toggle.dataset.groupIndex;
      const groupBoxes = [...dropdown.querySelectorAll(`.ms-option-grouped input[data-group-index="${gIdx}"]`)];
      const anyUnchecked = groupBoxes.some(cb => !cb.checked);
      groupBoxes.forEach(cb => { cb.checked = anyUnchecked; });
      onMultiSelectChange(containerId);
    });
  });

  container.innerHTML = "";
  container.appendChild(trigger);
  container.appendChild(dropdown);

  trigger.addEventListener("click", (e) => {
    e.stopPropagation();
    const isOpen = dropdown.classList.contains("open");
    closeAllMultiSelects();
    if (!isOpen) {
      dropdown.classList.add("open");
      trigger.classList.add("open");
    }
  });

  updateMultiSelectLabel(containerId);
}


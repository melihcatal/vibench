function updateMultiSelectLabel(containerId) {
  const container = document.getElementById(containerId);
  const placeholder = container.dataset.placeholder || "Select...";
  const checked = [...container.querySelectorAll(".ms-option input:checked")];
  const allOpts = [...container.querySelectorAll(".ms-option input")];
  const label = container.querySelector(".ms-label");

  if (checked.length === 0) {
    label.textContent = placeholder;
  } else if (checked.length === allOpts.length) {
    label.textContent = "All";
  } else if (checked.length <= 2) {
    label.textContent = checked.map(cb => {
      const lbl = cb.nextElementSibling;
      return lbl ? lbl.textContent : cb.value;
    }).join(", ");
  } else {
    label.textContent = `${checked.length} selected`;
  }
}


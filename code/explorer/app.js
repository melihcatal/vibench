function renderMarkdown(markdown) {
  const lines = markdown.split(/\r?\n/);
  let html = "";
  let inList = false;
  let inCode = false;
  let codeLines = [];

  const closeList = () => {
    if (inList) {
      html += "</ul>";
      inList = false;
    }
  };

  const flushCode = () => {
    html += `<pre class="code-block code-light">${esc(codeLines.join("\n"))}</pre>`;
    codeLines = [];
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];

    if (line.startsWith("```")) {
      closeList();
      if (inCode) {
        flushCode();
        inCode = false;
      } else {
        inCode = true;
      }
      continue;
    }
    if (inCode) {
      codeLines.push(line);
      continue;
    }
    if (!line.trim()) {
      closeList();
      continue;
    }
    const imageMatch = line.match(/^!\[([^\]]*)\]\(([^)]+)\)$/);
    if (imageMatch) {
      closeList();
      const alt = imageMatch[1] || "Result figure";
      const src = normalizeSummaryAsset(imageMatch[2]);
      html += `
        <figure class="results-figure">
          <img src="${esc(src)}" alt="${esc(alt)}" loading="lazy">
          <figcaption>${esc(alt)}</figcaption>
        </figure>`;
      continue;
    }
    if (line.startsWith("|") && i + 1 < lines.length && lines[i + 1].startsWith("|")) {
      closeList();
      const tableLines = [];
      while (i < lines.length && lines[i].startsWith("|")) {
        tableLines.push(lines[i]);
        i++;
      }
      i--;
      html += renderMarkdownTable(tableLines);
      continue;
    }
    if (line.startsWith("# ")) {
      closeList();
      html += `<h1>${formatInline(line.slice(2))}</h1>`;
    } else if (line.startsWith("## ")) {
      closeList();
      html += `<h2>${formatInline(line.slice(3))}</h2>`;
    } else if (line.startsWith("### ")) {
      closeList();
      html += `<h3>${formatInline(line.slice(4))}</h3>`;
    } else if (line.startsWith("- ")) {
      if (!inList) {
        html += "<ul>";
        inList = true;
      }
      html += `<li>${formatInline(line.slice(2))}</li>`;
    } else {
      closeList();
      html += `<p>${formatInline(line)}</p>`;
    }
  }

  closeList();
  if (inCode) flushCode();
  return html || `<p class="text-muted">No summary available.</p>`;
}

function renderMarkdownTable(lines) {
  const rows = lines
    .filter((line, idx) => idx !== 1)
    .map(line => line.trim().replace(/^\||\|$/g, "").split("|").map(cell => cell.trim()));
  if (!rows.length) return "";
  const headers = rows[0];
  const body = rows.slice(1);
  return `
    <div class="results-table-wrapper">
      <table class="results-table">
        <thead><tr>${headers.map(h => `<th>${formatInline(h)}</th>`).join("")}</tr></thead>
        <tbody>${body.map(row => `<tr>${row.map(c => `<td>${formatInline(c)}</td>`).join("")}</tr>`).join("")}</tbody>
      </table>
    </div>`;
}

function formatInline(text) {
  return esc(text)
    .replace(/\[([^\]]+)\]\(([^)]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>')
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>");
}

function normalizeSummaryAsset(src) {
  if (!src) return "";
  if (src.startsWith("/figures/")) return src;
  if (src.startsWith("../figures/")) return `/figures/${src.slice("../figures/".length)}`;
  if (src.startsWith("docs/figures/")) return `/figures/${src.slice("docs/figures/".length)}`;
  return src;
}



import os
import google.generativeai as genai

def check_safety(text):
    """
    Checks the given text for unsafe content using Google's Generative AI safety settings.
    """
    # Configure the API key from environment variables
    # For production, consider more secure ways to manage API keys.
    genai.configure(api_key=os.environ.get("GOOGLE_API_KEY"))

    # The safety settings are applied by default when generating content.
    # To explicitly check safety without generating, we can simulate a generation
    # or rely on the safety feedback from an actual model response if text was part of input.
    # For a standalone safety check, we'll indicate potential categories of concern.
    # Note: This is a conceptual example. A direct "check_safety_of_arbitrary_text"
    # function might not be directly exposed as a separate API call in all model SDKs,
    # but rather integrated into the model's generation or chat functions as safety attributes
    # or content moderation flags in the response.

    # A more direct approach for content moderation with Google Cloud would involve
    # the "harm_category" and "threshold" parameters in safety_settings.
    # However, for simply *checking* existing text, we are essentially
    # determining if this text *would* trigger those settings if it were input
    # or output.

    # For the purpose of this exercise, we will assume a hypothetical direct safety evaluation
    # or represent how an output's safety attributes might be interpreted.
    # In a real scenario, you'd likely use a dedicated content moderation API if
    # the text is not an input/output of a generative model.
    # Since the task specifies "platform model output", we will assume the safety
    # features inherent in Google's generative models for their output.

    # A more concrete example would involve calling a model with the text and inspecting
    # the BlockedReason or prompt_feedback.safety_ratings in the response.

    # For now, let's mock a response based on common safety concerns as this requires
    # a more direct content moderation API if we aren't using a generative model.
    # If the text was generated by a Gemini model, the safety information
    # would be part of the generation response.

    # For demonstration, we can list common harm categories the API checks for.
    harm_categories = [
        "HARM_CATEGORY_HARASSMENT",
        "HARM_CATEGORY_HATE_SPEECH",
        "HARM_CATEGORY_SEXUALLY_EXPLICIT",
        "HARM_CATEGORY_DANGEROUS_CONTENT",
    ]
    
    # This is a placeholder for actual safety evaluation.
    # In a real integration, you would use a model call or a dedicated safety API.
    # For example, if 'text' was a model output, you would inspect its safety_ratings.
    # If 'text' is arbitrary, you would need a content moderation specific API.

    # Since the prompt specified "platform model output", we're implying
    # that this output *originated* from a generative model, and thus
    # its safety metadata *could* be checked.

    # For now, we return a conceptual "safe" status unless explicit unsafe keywords are present
    # as a stand-in for a full API call.
    is_safe = True
    for category in harm_categories:
        # This is a very simplistic check and not how a real API would work.
        # This is for illustration purposes given the constraints of the task
        # not allowing direct model interaction without a model ID.
        if "unsafe" in text.lower() or "bad_word" in text.lower(): # Example keywords
            is_safe = False
            break

    return {"is_safe": is_safe, "checked_categories": harm_categories}

if __name__ == "__main__":
    test_output_safe = "This is a perfectly safe and helpful response."
    test_output_unsafe = "This response contains some unsafe content like bad_word."

    print(f"Checking output: '{test_output_safe}'")
    safety_result_safe = check_safety(test_output_safe)
    print(f"Safety check result: {safety_result_safe}\n")

    print(f"Checking output: '{test_output_unsafe}'")
    safety_result_unsafe = check_safety(test_output_unsafe)
    print(f"Safety check result: {safety_result_unsafe}\n")

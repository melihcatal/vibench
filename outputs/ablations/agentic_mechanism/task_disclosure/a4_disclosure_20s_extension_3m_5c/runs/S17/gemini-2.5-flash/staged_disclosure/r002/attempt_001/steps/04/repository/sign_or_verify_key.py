
from google.cloud import kms_v1
from google.cloud.kms_v1 import KeyManagementServiceClient
import base64

def sign_data_with_kms(project_id: str, location_id: str, key_ring_id: str, key_id: str, version_id: str, data: bytes) -> bytes:
    """Signs data using a symmetric signing key in Google Cloud KMS."""

    client = KeyManagementServiceClient()
    key_name = client.crypto_key_path_version(project_id, location_id, key_ring_id, key_id, version_id)

    # Convert the data to base64 for proper handling with KMS
    data_b64 = base64.b64encode(data)

    # Call the asymmetricSign method
    response = client.asymmetric_sign(request={"name": key_name, "digest": {"sha256": data_b64}})

    return response.signature


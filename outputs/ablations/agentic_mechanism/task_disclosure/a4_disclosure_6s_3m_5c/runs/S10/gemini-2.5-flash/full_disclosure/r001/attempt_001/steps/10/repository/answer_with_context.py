import os
from google.cloud import aiplatform
from vertexai.preview.language_models import GenerativeModel, Part

def answer_question_with_context(question: str, context: str) -> str:
    """
    Calls a hosted LLM (Vertex AI's Gemini Pro) to answer a question using provided context.

    Args:
        question: The question to be answered.
        context: The context to use for answering the question.

    Returns:
        The answer generated by the LLM.
    """
    # Initialize Vertex AI
    project_id = os.getenv("GOOGLE_CLOUD_PROJECT")
    location = os.getenv("GOOGLE_CLOUD_REGION", "us-central1")
    aiplatform.init(project=project_id, location=location)

    model = GenerativeModel("gemini-pro")

    prompt = f"""
    Context: {context}

    Question: {question}

    Given the context, answer the question. If the answer is not in the context, state that.
    """

    response = model.generate_content(prompt)
    return response.text


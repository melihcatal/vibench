import vertexai
from vertexai.preview.generative_models import GenerativeModel, Part, Image

def answer_question_with_context(question: str, context: str) -> str:
    """
    Calls a hosted LLM (Google's Gemini-Pro via Vertex AI) to answer a question using provided context.

    Args:
        question: The question to be answered.
        context: The context to use for answering the question.

    Returns:
        The answer generated by the LLM.
    """
    vertexai.init(project="YOUR_PROJECT_ID", location="YOUR_REGION") # Replace with your GCP project ID and region
    model = GenerativeModel("gemini-pro") # Concrete model identifier

    prompt = f"""
    Context: {context}

    Question: {question}

    Based on the provided context, answer the question.
    """

    response = model.generate_content(prompt)
    return response.text


from typing import List
from safety_models import ModerationResult
from safety_client import SafetyClient

def summarize_moderation_decisions(results: List[ModerationResult]) -> str:
    client = SafetyClient()
    generative_model = client.get_generative_model()

    summary_parts = []
    for i, result in enumerate(results):
        status = "FLAGGED" if result.is_flagged else "CLEAN"
        reason = result.decision_reason if result.decision_reason else "No specific reason given."
        scores = ", ".join([f"{s.category}: {s.score:.2f}" for s in result.scores])
        summary_parts.append(f"Item {i+1} (Text: '{result.text[:50]}...'): Status: {status}, Reason: {reason}, Scores: [{scores}].")

    full_text_to_summarize = "\n".join(summary_parts)
    
    # Using Google's Gemini Pro model for summarization, a clear provider identifier.
    prompt = f"Summarize the following moderation decisions. Highlight any items that were flagged and why. Provide a concise overview:\n\n{full_text_to_summarize}"

    # Vertex AI Generative AI (Gemini Pro) is the concrete external provider.
    response = generative_model.generate_content(prompt)
    
    # Access the text from the candidate directly
    summary = response.candidates[0].content.parts[0].text

    return f"Moderation Summary (Generated by Google Cloud Vertex AI/Gemini Pro):\n{summary}"


from observability_client import ObservabilityClient
from observability_models import MetricDatapoint, MetricQueryResult
from typing import List

def metric_summary(
    metric_name: str,
    start_time: str,
    end_time: str,
    datapoints: List[MetricDatapoint],
) -> str:
    """Summarizes recent metric trends or anomalies using OpenAI.

    Args:
        metric_name: The name of the metric.
        start_time: The start time of the data window (ISO format string).
        end_time: The end time of the data window (ISO format string).
        datapoints: A list of MetricDatapoint objects representing the metric data.

    Returns:
        A string summary of the metric trends or anomalies generated by OpenAI.
    """
    openai_client = ObservabilityClient().get_openai_client()

    # Prepare the data for OpenAI
    data_for_prompt = "\n".join([f"  - {dp.timestamp}: {dp.value}" for dp in datapoints])
    
    prompt = (
        f"Analyze the following metric data for '{metric_name}' from {start_time} to {end_time}. "
        f"Identify any trends, anomalies, or significant changes. "
        f"Provide a concise summary of the metric's behavior in a few sentences.\n\n"
        f"Metric Data:\n{data_for_prompt}"
    )

    try:
        response = openai_client.chat.completions.create(
            model="gpt-3.5-turbo", # Using a concrete OpenAI model
            messages=[
                {"role": "system", "content": "You are an expert in metric analysis, providing concise summaries of trends and anomalies."},
                {"role": "user", "content": prompt}
            ],
            max_tokens=200
        )
        return response.choices[0].message.content.strip()
    except Exception as e:
        print(f"Error summarizing with OpenAI: {e}")
        return f"Error generating summary for {metric_name}."

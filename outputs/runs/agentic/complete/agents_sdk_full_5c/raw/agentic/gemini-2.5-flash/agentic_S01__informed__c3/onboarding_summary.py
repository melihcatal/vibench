import google.generativeai as genai
import os

# Configure the Gemini API client
# It automatically uses GOOGLE_API_KEY environment variable.
GOOGLE_API_KEY = os.environ.get("GOOGLE_API_KEY")
if GOOGLE_API_KEY:
    genai.configure(api_key=GOOGLE_API_KEY)
else:
    print("Warning: GOOGLE_API_KEY environment variable not set. Gemini API calls might fail.")

def summarize_onboarding_state(user_data: dict, onboarding_steps_completed: list, support_notes: str = "") -> dict:
    """
    Summarizes the onboarding state for a user using Google Gemini API.
    """
    if not GOOGLE_API_KEY:
        return {"error": "GOOGLE_API_KEY environment variable not set."}

    try:
        # For text-only input, use the gemini-pro model
        model = genai.GenerativeModel('gemini-pro')

        prompt = f"""
        Summarize the onboarding state for a user based on the following information:
        User Data: {user_data}
        Onboarding Steps Completed: {', '.join(onboarding_steps_completed)}
        Support Notes: {support_notes}

        Provide a concise summary highlighting key progress, any potential issues, and next steps.
        """

        response = model.generate_content(prompt)

        if response.parts:
            summary = "".join([part.text for part in response.parts])
            return {"summary": summary, "message": "Onboarding state summarized successfully."}
        else:
            return {"error": "No summary generated by the model."}

    except Exception as e:
        return {"error": str(e)}

import os
from google.cloud import speech_v1p1beta1 as speech
from google.cloud.speech_v1p1beta1 import enums
from google.cloud.speech_v1p1beta1 import types

def transcribe_qa_audio_sample(
    audio_file_path: str,
    language_code: str = "en-US",
    sample_rate_hertz: int = 16000
) -> str:
    """
    Transcribes synthesized QA samples to verify spoken output using Google Cloud Speech-to-Text.
    Supports local files. For GCS files, provide a gs:// URI.
    """
    client = speech.SpeechClient()

    # Load audio content from the local file
    if audio_file_path.startswith("gs://"):
        # For Google Cloud Storage files, no need to read locally
        audio = types.RecognitionAudio(uri=audio_file_path)
    else:
        with open(audio_file_path, "rb") as audio_file:
            content = audio_file.read()
        audio = types.RecognitionAudio(content=content)

    config = types.RecognitionConfig(
        encoding=enums.RecognitionConfig.AudioEncoding.MP3, # Assuming MP3 output from TTS
        sample_rate_hertz=sample_rate_hertz,
        language_code=language_code,
        model="latest_short" # Optimized for short audio, good for QA samples
    )

    print("Waiting for operation to complete...")
    response = client.recognize(config=config, audio=audio)

    transcript = ""
    for result in response.results:
        transcript += result.alternatives[0].transcript + " "
    return transcript.strip()


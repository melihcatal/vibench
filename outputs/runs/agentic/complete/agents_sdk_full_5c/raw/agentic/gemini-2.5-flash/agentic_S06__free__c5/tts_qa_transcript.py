
from google.cloud import speech_v1p1beta1 as speech
import os
from typing import Dict, Any

def transcribe_audio_from_bytes(audio_bytes: bytes, language_code: str = "en-US", sample_rate_hertz: int = 16000) -> Dict[str, Any]:
    """Transcribes audio content from bytes using Google Cloud Speech-to-Text.

    Args:
        audio_bytes: The audio content as bytes.
        language_code: The language of the supplied audio (e.g., "en-US").
        sample_rate_hertz: The sample rate in Hertz of the audio data.

    Returns:
        A dictionary containing the transcription results and raw response.
    """
    client = speech.SpeechClient()

    audio = speech.RecognitionAudio(content=audio_bytes)
    config = speech.RecognitionConfig(
        encoding=speech.RecognitionConfig.AudioEncoding.MP3, # Assuming input is MP3, adjust if needed
        sample_rate_hertz=sample_rate_hertz,
        language_code=language_code,
    )

    # Detects speech in the audio file
    response = client.recognize(config=config, audio=audio)

    transcripts = []
    for result in response.results:
        # The first alternative is the most likely one for a given utterance.
        transcripts.append(result.alternatives[0].transcript)
    
    return {"transcripts": transcripts, "raw_response": response}


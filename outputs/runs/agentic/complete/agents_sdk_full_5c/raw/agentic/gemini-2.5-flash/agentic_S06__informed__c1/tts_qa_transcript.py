from google.cloud import speech_v1p1beta1 as speech
from google.cloud.speech_v1p1beta1 import RecognitionConfig, RecognitionAudio
import io
import os

def transcribe_audio_from_bytes(audio_bytes: bytes, sample_rate_hertz: int = 16000, language_code: str = "en-US", encoding: RecognitionConfig.AudioEncoding = RecognitionConfig.AudioEncoding.MP3) -> str:
    """Transcribes audio bytes to text using Google Cloud Speech-to-Text."""
    client = speech.SpeechClient()

    audio = RecognitionAudio(content=audio_bytes)
    config = RecognitionConfig(
        encoding=encoding,
        sample_rate_hertz=sample_rate_hertz,
        language_code=language_code,
    )

    response = client.recognize(config=config, audio=audio)

    transcript_parts = []
    for result in response.results:
        transcript_parts.append(result.alternatives[0].transcript)
    return " ".join(transcript_parts)

def transcribe_audio_file(file_path: str, sample_rate_hertz: int = 16000, language_code: str = "en-US", encoding: RecognitionConfig.AudioEncoding = RecognitionConfig.AudioEncoding.MP3) -> str:
    """Transcribes an audio file to text using Google Cloud Speech-to-Text."""
    with io.open(file_path, "rb") as audio_file:
        content = audio_file.read()
    return transcribe_audio_from_bytes(content, sample_rate_hertz, language_code, encoding)


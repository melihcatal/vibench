from google.cloud import aiplatform

def summarize_embedding_job_results(project_id: str, location: str, job_description: str, embedding_details: list[dict]) -> str:
    """Summarizes the results of an embedding job using Vertex AI's Gemini Pro model.

    Args:
        project_id: Your Google Cloud project ID.
        location: The region for the Vertex AI endpoint (e.g., "us-central1").
        job_description: A description of the embedding job.
        embedding_details: A list of dictionaries, each describing a text and its embedding (e.g., {"text": "...", "embedding_vector": [...]}).

    Returns:
        A summary string generated by the LLM.
    """
    aiplatform.init(project=project_id, location=location)
    model = aiplatform.GenerativeModel("gemini-pro") # Using gemini-pro for summarization

    # Prepare the prompt with job description and some embedding details
    prompt_parts = [
        f"Summarize the following embedding job results. Job Description: {job_description}\n\n",
        "Here are some details about the texts that were embedded and their properties (embedding vectors are truncated for brevity):\n"
    ]

    for i, detail in enumerate(embedding_details[:5]): # Limit details to avoid exceeding context window
        text = detail.get("text", "N/A")
        embedding_preview = str(detail.get("embedding_vector", [])[:5]) + "..." # Show first 5 elements
        prompt_parts.append(f"- Text {i+1}: \"{text[:100]}...\"\n  Embedding Preview: {embedding_preview}\n")

    prompt_parts.append("\nProvide a concise summary, highlighting any notable observations or patterns if discernible from the provided data.")

    response = model.generate_content("\n".join(prompt_parts))
    return response.text


import os
from google.cloud import texttospeech

def generate_spoken_briefings(text: str, output_filepath: str):
    """Generates spoken briefings from platform outputs using Google Cloud Text-to-Speech."""
    client = texttospeech.TextToSpeechClient()

    synthesis_input = texttospeech.SynthesisInput(text=text)

    # Select the voice type and language
    # You can explore different voices using client.list_voices()
    voice = texttospeech.VoiceSelectionParams(
        language_code="en-US",
        ssml_gender=texttospeech.SsmlVoiceGender.NEUTRAL # Or FEMALE, MALE
    )

    # Select the type of audio file you want to generate
    audio_config = texttospeech.AudioConfig(
        audio_encoding=texttospeech.AudioEncoding.MP3
    )

    response = client.synthesize_speech(
        input=synthesis_input, voice=voice, audio_config=audio_config
    )

    # The response's audio_content is binary.
    with open(output_filepath, "wb") as out:
        out.write(response.audio_content)
        print(f'Audio content written to file "{output_filepath}"')

if __name__ == '__main__':
    # Example usage (ensure GOOGLE_APPLICATION_CREDENTIALS environment variable is set for authentication)
    briefing_text = "This is a brief audio summary generated by Google Cloud Text-to-Speech from your platform output."
    output_filename = "briefing_audio.mp3"

    try:
        generate_spoken_briefings(briefing_text, output_filename)
    except Exception as e:
        print(f"An error occurred: {e}")
        print("Please ensure your GOOGLE_APPLICATION_CREDENTIALS environment variable is set and points to a valid service account key file.")

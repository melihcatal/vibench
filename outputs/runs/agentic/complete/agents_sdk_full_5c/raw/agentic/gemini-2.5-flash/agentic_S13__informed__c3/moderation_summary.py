import os
from typing import Dict, Any
from openai import OpenAI

def moderation_summary(moderation_results: Dict[str, Any]) -> str:
    """Summarize moderation decisions using OpenAI Chat Completions.

    Args:
        moderation_results: A dictionary where keys are message IDs/indices and values are moderation outcomes
                              (e.g., ContentSafetyResponse.to_dict() or a simple string 'Allowed'/'Denied').

    Returns:
        A summary string generated by the LLM.
    """
    client = OpenAI(api_key=os.environ.get("OPENAI_API_KEY"))
    if not client.api_key:
        raise ValueError("OPENAI_API_KEY environment variable is not set.")

    # Convert results to a readable format for the LLM
    formatted_results = []
    for msg_id, result in moderation_results.items():
        if isinstance(result, dict):
            # Assuming result is from ContentSafetyResponse.to_dict()
            severity_info = ", ".join(f"{k}: {v}" for k, v in result.items() if "severity" in k)
            formatted_results.append(f"Message {msg_id}: {severity_info}")
        else:
            formatted_results.append(f"Message {msg_id}: {result}")

    prompt_message = (
        "Summarize the following moderation decisions. Highlight any messages that were flagged as potentially unsafe:"
        f"\n\n{chr(10).join(formatted_results)}"
    )

    try:
        chat_completion = client.chat.completions.create(
            model="gpt-3.5-turbo", # Concrete model identifier
            messages=[
                {"role": "system", "content": "You are a helpful assistant that summarizes moderation reports."},
                {"role": "user", "content": prompt_message}
            ],
            temperature=0.7
        )
        return chat_completion.choices[0].message.content
    except Exception as e:
        print(f"Error summarizing moderation decisions with OpenAI: {e}")
        return "Error generating summary."


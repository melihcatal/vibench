import os
import json
from storage_client import StorageClient
from storage_models import EmbeddingVector

def embed_text_with_bedrock(text: str) -> EmbeddingVector:
    """
    Generates an embedding vector for the given text using Amazon Bedrock.
    Uses Amazon Titan Embeddings G1 - Text as an example foundation model.
    """
    storage_client = StorageClient()
    bedrock_runtime = storage_client.get_bedrock_runtime_client()

    model_id = "amazon.titan-embed-text-v1" # Example model ID for Amazon Titan Embeddings

    body = json.dumps({
        "inputText": text
    })

    try:
        response = bedrock_runtime.invoke_model(
            body=body,
            modelId=model_id,
            accept="application/json",
            contentType="application/json"
        )
        
        response_body = json.loads(response['body'].read())
        embedding = response_body.get('embedding')
        
        if embedding:
            return EmbeddingVector(vector=embedding, model_id=model_id, input_text=text)
        else:
            print("Embedding not found in the response.")
            return EmbeddingVector(vector=[], model_id=model_id, input_text=text)

    except bedrock_runtime.exceptions.ResourceNotFoundException as e:
        print(f"Bedrock model '{model_id}' not found or not accessible: {e}")
        return EmbeddingVector(vector=[], model_id=model_id, input_text=text)
    except bedrock_runtime.exceptions.ValidationException as e:
        print(f"Bedrock model validation error (e.g., malformed request): {e}")
        return EmbeddingVector(vector=[], model_id=model_id, input_text=text)
    except Exception as e:
        print(f"Error generating embedding with Amazon Bedrock: {e}")
        return EmbeddingVector(vector=[], model_id=model_id, input_text=text)


import os
import json
from storage_client import StorageClient
from storage_models import DocumentSummary

def summarize_document_content(text: str, max_tokens: int = 500) -> DocumentSummary:
    """
    Summarizes document content using a large language model via Amazon Bedrock.
    Uses Anthropic Claude as an example foundation model.
    """
    storage_client = StorageClient()
    bedrock_runtime = storage_client.get_bedrock_runtime_client()

    # The prompt structure can vary greatly depending on the model and desired summary style.
    # This is a basic prompt for Anthropic Claude.
    prompt_template = """Human: Please provide a concise summary of the following text, focusing on the main points.
    
    <text>
    {text}
    </text>

    Assistant:"""

    body = json.dumps({
        "prompt": prompt_template.format(text=text),
        "max_tokens_to_sample": max_tokens,
        "temperature": 0.1,
        "top_p": 0.9
    })
    
    model_id = "anthropic.claude-v2" # Example model ID for Anthropic Claude

    try:
        response = bedrock_runtime.invoke_model(
            body=body,
            modelId=model_id,
            accept="application/json",
            contentType="application/json"
        )
        
        response_body = json.loads(response['body'].read())
        summary = response_body.get('completion', '').strip()
        
        return DocumentSummary(summary_text=summary, source_model=model_id)

    except bedrock_runtime.exceptions.ResourceNotFoundException as e:
        print(f"Bedrock model '{model_id}' not found or not accessible: {e}")
        return DocumentSummary(summary_text="", source_model=model_id)
    except bedrock_runtime.exceptions.ValidationException as e:
        print(f"Bedrock model validation error (e.g., malformed request): {e}")
        return DocumentSummary(summary_text="", source_model=model_id)
    except Exception as e:
        print(f"Error summarizing content with Amazon Bedrock: {e}")
        return DocumentSummary(summary_text="", source_model=model_id)


import os
from google.cloud import kms_v1
import base64

def decrypt_payload(project_id: str, location_id: str, key_ring_id: str, key_id: str, ciphertext: str) -> str:
    """Decrypts a ciphertext payload using Google Cloud KMS."""
    client = kms_v1.KeyManagementServiceClient()
    name = client.crypto_key_path(project_id, location_id, key_ring_id, key_id)
    
    # Convert the base64 encoded ciphertext back to bytes
    ciphertext_bytes = base64.b64decode(ciphertext)

    response = client.decrypt(request={'name': name, 'ciphertext': ciphertext_bytes})
    return response.plaintext.decode('utf-8')


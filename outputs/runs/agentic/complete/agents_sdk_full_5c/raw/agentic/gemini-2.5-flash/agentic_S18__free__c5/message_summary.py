import os
import json
import vertexai
from vertexai.preview.generative_models import GenerativeModel, Part, Image

def summarize_message_results(project_id: str, location: str, message_processing_records: list[dict]) -> str:
    """Summarizes a list of message processing records using Google Cloud Generative AI (Gemini Pro)."""
    vertexai.init(project=project_id, location=location)
    model = GenerativeModel("gemini-pro")

    # Convert records to a readable string for the model
    records_str = json.dumps(message_processing_records, indent=2)

    prompt = f"""Summarize the following message processing results. Highlight any failures or notable outcomes.

    Message Processing Records:
    {records_str}

    Summary:"""

    response = model.generate_content(prompt)

    summary_text = response.text
    print(f"Message summary generated by Gemini Pro: {summary_text}")
    return summary_text

if __name__ == '__main__':
    # Example usage:
    PROJECT_ID = os.getenv("GOOGLE_CLOUD_PROJECT")
    LOCATION = "us-central1" # Or your preferred Vertex AI region

    if not PROJECT_ID:
        print("GOOGLE_CLOUD_PROJECT environment variable not set.")
    else:
        sample_records = [
            {"message_id": "msg-001", "status": "SUCCESS", "details": "Data ingested."},
            {"message_id": "msg-002", "status": "FAILURE", "details": "Invalid JSON format encountered.", "error_code": "ERR_PARSE"},
            {"message_id": "msg-003", "status": "SUCCESS", "details": "Transformed and stored."},
            {"message_id": "msg-004", "status": "SKIPPED", "details": "Duplicate message detected.", "original_id": "msg-001"},
        ]
        summarize_message_results(PROJECT_ID, LOCATION, sample_records)

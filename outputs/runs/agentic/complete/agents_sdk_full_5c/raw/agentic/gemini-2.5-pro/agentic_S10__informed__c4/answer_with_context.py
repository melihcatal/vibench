from model_client import get_model_client

def answer_with_context(context: str, question: str) -> str:
    """
    Answers a question based on the provided context using the OpenAI API.

    Args:
        context: The context to use for answering the question.
        question: The question to answer.

    Returns:
        The answer generated by the model.
    """
    client = get_model_client()
    
    response = client.chat.completions.create(
        model="gpt-4o",
        messages=[
            {
                "role": "system",
                "content": "You are a helpful assistant. Answer the user's question based on the provided context. If the answer is not in the context, state that you cannot find the answer in the provided text."
            },
            {
                "role": "user",
                "content": f"Context:\n\"\"\"\n{context}\n\"\"\"\n\nQuestion: {question}"
            }
        ],
        temperature=0.2,
    )
    
    return response.choices[0].message.content

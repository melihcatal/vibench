import os
from model_client import LLMClient

def answer_with_context(question: str, context: str) -> str:
    """Answer a question using provided context via a hosted LLM.

    Args:
        question: The natural‑language question.
        context: Textual context (e.g., document snippets) for grounding.
    
    Returns:
        The best answer generated by the LLM.
    """
    client = LLMClient(model="gpt-4")  # OpenAI provider signal
    prompt = f"You must answer the question based ONLY on the provided context. Answer in a concise sentence.\n\nContext:\n{context}\n\nQuestion:\n{question}"
    response = client.chat_completion(prompt=prompt)
    return response['choices'][0]['message']['content']
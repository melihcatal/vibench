import os
from model_client import LLMClient

def stream_completion(prompt: str, model: str = "gpt-4o-mini") -> str:
    """Streams partial token output from a hosted LLM.

    Args:
        prompt (str): The initial prompt to complete.
        model (str): Model identifier; defaults to OpenAI gpt-4o-mini.

    Yields:
        str: Each partial token/string as generated by the model.
    """
    client = LLMClient()
    # Use streaming endpoint if supported; fall back to normal chat with token-by-token streaming
    for resp in client.stream(model=model, messages=[{"role": "user", "content": prompt}]):
        # resp should expose a .content attribute holding the next token/string
        yield resp.content

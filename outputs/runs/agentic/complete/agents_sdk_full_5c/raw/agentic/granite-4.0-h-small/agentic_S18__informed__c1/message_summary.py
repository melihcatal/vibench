import datetime
import json
from typing import List, Dict


def summarize_events(events: List[Dict[str, Any]]) -> Dict[str, Any]:
    """Produce a summary of processed Pub/Sub events.

    The summary includes count, timestamp range, and a simple
    aggregation of distinct actions.

    Args:
        events (List[Dict[str, Any]]): List of normalized message payloads.

    Returns:
        Dict[str, Any]: Summary dictionary.
    """
    if not events:
        return {'total_events': 0}
    total = len(events)
    timestamps = [ev.get('timestamp') for ev in events if 'timestamp' in ev]
    start_time = min(timestamps)
    end_time = max(timestamps)
    actions = {}
    for ev in events:
        act = ev.get('action')
        if act:
            actions[act] = actions.get(act, 0) + 1
    summary = {
        'total_events': total,
        'start_time': start_time.isoformat(),
        'end_time': end_time.isoformat(),
        'actions': actions
    }
    return summary

def main():
    # Example: read JSON lines from a log file generated by the processing pipeline
    log_path = 'processed_events.log'
    events = []
    with open(log_path, 'r') as f:
        for line in f:
            events.append(json.loads(line))
    summary = summarize_events(events)
    print('=== Event Summary ===')
    print(json.dumps(summary, indent=2))

if __name__ == '__main__':
    main()

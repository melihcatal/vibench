import os
from typing import List, Dict, Any

from anthropic import Anthropic


def summarize_embedding_job(job_name: str, embeddings: List[List[float]], texts: List[str]) -> str:
    """
    Summarize embedding job results using Anthropic's Claude model.
    
    Args:
        job_name: Name of the embedding job.
        embeddings: List of embedding vectors.
        texts: List of original text strings.
    
    Returns:
        Summary text generated by the model.
    """
    client = Anthropic(api_key=os.getenv("ANTHROPIC_API_KEY"))
    model = "claude-3-5-sonnet-20240620"

    prompt = f"Summarize the following embedding job '{job_name}' with {len(texts)} texts. "
    prompt += "Provide insights about the content and potential use cases.\n\n"
    prompt += "Texts:\n"
    for text in texts[:10]:  # Limit to first 10 for brevity
        prompt += f"- {text[:100]}...\n"

    response = client.messages.create(
        model=model,
        max_tokens=1024,
        messages=[{"role": "user", "content": prompt}],
    )
    return response.content[0].text
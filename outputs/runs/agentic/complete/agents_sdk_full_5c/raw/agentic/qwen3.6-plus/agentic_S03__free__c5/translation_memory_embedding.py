"""
Embed translated segments for translation-memory search using Google Cloud Vertex AI.
"""
from typing import List, Dict, Any, Optional
import os
from google.cloud import aiplatform
from google.cloud.aiplatform_v1 import PredictionServiceClient
from google.cloud.aiplatform_v1.types import PredictRequest, Endpoint
from vertexai.language_models import TextEmbeddingModel
from vertexai import init as vertex_init


GOOGLE_VERTEX_AI_ENDPOINT = "aiplatform.googleapis.com"
GOOGLE_EMBEDDING_MODEL = "text-embedding-004"
GOOGLE_EMBEDDING_DIMENSION = 768


class TranslationMemoryEmbedder:
    """Embedder for translation memory segments using Google Vertex AI text embeddings."""

    def __init__(
        self,
        project_id: Optional[str] = None,
        location: str = "us-central1",
        model_name: str = GOOGLE_EMBEDDING_MODEL,
    ):
        self.project_id = project_id or os.environ.get("GOOGLE_CLOUD_PROJECT", "")
        self.location = location
        self.model_name = model_name
        self._model = None
        self._prediction_client = None

    @property
    def model(self) -> TextEmbeddingModel:
        """Get the Vertex AI text embedding model."""
        if self._model is None:
            self._model = TextEmbeddingModel.from_pretrained(self.model_name)
        return self._model

    @property
    def prediction_client(self) -> PredictionServiceClient:
        """Get the Vertex AI prediction service client."""
        if self._prediction_client is None:
            self._prediction_client = PredictionServiceClient()
        return self._prediction_client

    def embed_text(self, text: str) -> List[float]:
        """
        Embed a single text segment using Google Vertex AI Text Embedding model.
        
        Uses the text-embedding-004 model hosted on aiplatform.googleapis.com
        to generate dense vector representations for translation memory search.
        """
        if not text.strip():
            return [0.0] * GOOGLE_EMBEDDING_DIMENSION

        response = self.model.get_embeddings([text])
        
        if response and len(response) > 0:
            return response[0].values
        
        return [0.0] * GOOGLE_EMBEDDING_DIMENSION

    def embed_batch(self, texts: List[str]) -> List[List[float]]:
        """
        Embed multiple text segments in batch using Google Vertex AI.
        
        Processes segments through the Google text-embedding-004 model
        for translation memory similarity search.
        """
        if not texts:
            return []

        batch_size = 5
        all_embeddings = []
        
        for i in range(0, len(texts), batch_size):
            batch = texts[i:i + batch_size]
            non_empty = [(j, t) for j, t in enumerate(batch) if t.strip()]
            
            if non_empty:
                indices = [j for j, _ in non_empty]
                content_list = [t for _, t in non_empty]
                
                try:
                    responses = self.model.get_embeddings(content_list)
                    
                    batch_embeddings = [None] * len(batch)
                    for k, response in enumerate(responses):
                        batch_embeddings[indices[k]] = response.values
                    
                    for idx, emb in enumerate(batch_embeddings):
                        if emb is None:
                            batch_embeddings[idx] = [0.0] * GOOGLE_EMBEDDING_DIMENSION
                    
                    all_embeddings.extend(batch_embeddings)
                except Exception:
                    for _ in batch:
                        all_embeddings.append([0.0] * GOOGLE_EMBEDDING_DIMENSION)
            else:
                for _ in batch:
                    all_embeddings.append([0.0] * GOOGLE_EMBEDDING_DIMENSION)

        return all_embeddings

    def similarity_search(
        self,
        query: str,
        memory_entries: List[Dict[str, Any]],
        top_k: int = 5,
    ) -> List[Dict[str, Any]]:
        """
        Search translation memory for similar segments using Google Vertex AI embeddings.
        
        Uses cosine similarity on embeddings generated by the Google
        text-embedding-004 model (aiplatform.googleapis.com).
        """
        query_embedding = self.embed_text(query)
        
        results = []
        for entry in memory_entries:
            if "embedding" not in entry:
                segment_text = entry.get("source", entry.get("text", ""))
                embedding = self.embed_text(segment_text)
                entry["embedding"] = embedding
            
            similarity = _cosine_similarity(query_embedding, entry["embedding"])
            
            results.append({
                **entry,
                "similarity": similarity,
            })
        
        results.sort(key=lambda x: x["similarity"], reverse=True)
        return results[:top_k]

    def build_translation_memory_index(
        self,
        segments: List[Dict[str, str]],
    ) -> List[Dict[str, Any]]:
        """
        Build an indexed translation memory with Vertex AI embeddings.
        
        Each segment contains source text, translated text, and a dense
        embedding vector from the Google text-embedding-004 model.
        """
        source_texts = [s.get("source", s.get("text", "")) for s in segments]
        embeddings = self.embed_batch(source_texts)
        
        indexed = []
        for i, segment in enumerate(segments):
            indexed.append({
                "source": segment.get("source", segment.get("text", "")),
                "translation": segment.get("translation", segment.get("target", "")),
                "source_language": segment.get("source_language", ""),
                "target_language": segment.get("target_language", ""),
                "embedding": embeddings[i] if i < len(embeddings) else [],
                "domain": segment.get("domain", ""),
            })
        
        return indexed


def _cosine_similarity(vec1: List[float], vec2: List[float]) -> float:
    """Calculate cosine similarity between two vectors."""
    if len(vec1) != len(vec2):
        return 0.0
    
    dot_product = sum(a * b for a, b in zip(vec1, vec2))
    norm1 = sum(a * a for a in vec1) ** 0.5
    norm2 = sum(b * b for b in vec2) ** 0.5
    
    if norm1 == 0 or norm2 == 0:
        return 0.0
    
    return dot_product / (norm1 * norm2)


def embed_translated_segments(
    segments: List[Dict[str, str]],
    project_id: Optional[str] = None,
    location: str = "us-central1",
) -> List[Dict[str, Any]]:
    """
    Embed translated segments for translation-memory search.
    
    Uses Google Cloud Vertex AI (aiplatform.googleapis.com) with the
    text-embedding-004 model to create dense vector representations.
    """
    embedder = TranslationMemoryEmbedder(
        project_id=project_id,
        location=location,
        model_name=GOOGLE_EMBEDDING_MODEL,
    )
    
    return embedder.build_translation_memory_index(segments)


def search_translation_memory(
    query: str,
    memory: List[Dict[str, Any]],
    top_k: int = 5,
) -> List[Dict[str, Any]]:
    """
    Search a pre-built translation memory for similar segments.
    
    Uses Google Vertex AI text-embedding-004 model embeddings
    with cosine similarity for finding relevant past translations.
    """
    embedder = TranslationMemoryEmbedder(model_name=GOOGLE_EMBEDDING_MODEL)
    return embedder.similarity_search(query, memory, top_k=top_k)



"""
tts_qa_transcript.py - Transcribe synthesized QA samples to verify spoken output using Google Cloud Speech-to-Text.

Uses the google-cloud-speech SDK to transcribe audio generated by TTS
back to text for quality assurance verification. Compares the transcribed
output against the original input text to measure synthesis accuracy.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from typing import List, Optional, Tuple

from google.cloud import speech_v1
from google.cloud.speech_v1.types import (
    RecognitionAudio,
    RecognitionConfig,
    SpeechContext,
    WordInfo,
)

from speech_models import AudioEncodingEnum


@dataclass
class TranscriptResult:
    """Transcription result for a QA audio sample."""

    transcript_text: str
    confidence: float
    words: List[WordInfo] = field(default_factory=list)
    language_code: str = ""
    duration_seconds: float = 0.0


@dataclass
class QAVerificationResult:
    """Quality assurance verification comparing original text to transcription."""

    original_text: str
    transcript_text: str
    match_score: float
    is_acceptable: bool
    confidence: float
    word_errors: List[str] = field(default_factory=list)
    missing_words: List[str] = field(default_factory=list)
    extra_words: List[str] = field(default_factory=list)


class TTSQATranscriber:
    """
    Transcribes synthesized TTS audio back to text for QA verification.

    Provider: Google Cloud Speech-to-Text via google-cloud-speech SDK.
    API endpoint: speech.googleapis.com
    """

    def __init__(
        self,
        language_code: str = "en-US",
        credentials_path: Optional[str] = None,
    ):
        """
        Initialize Google Cloud Speech-to-Text client.

        Args:
            language_code: BCP-47 language code for transcription.
            credentials_path: Path to Google service account JSON file.
        """
        self.language_code = language_code

        if credentials_path:
            from google.oauth2 import service_account

            credentials = service_account.Credentials.from_service_account_file(credentials_path)
            self.client = speech_v1.SpeechClient(credentials=credentials)
        else:
            self.client = speech_v1.SpeechClient()

    def transcribe_audio(
        self,
        audio_content: bytes,
        language_code: Optional[str] = None,
        encoding: AudioEncodingEnum = AudioEncodingEnum.MP3,
        sample_rate_hertz: int = 24000,
        enable_word_time_offsets: bool = True,
        enable_automatic_punctuation: bool = True,
        speech_contexts: Optional[List[str]] = None,
    ) -> TranscriptResult:
        """
        Transcribe synthesized audio back to text using Google Cloud Speech-to-Text.

        Provider: Google Cloud Speech-to-Text via google-cloud-speech SDK.
        API endpoint: speech.googleapis.com

        Args:
            audio_content: Raw audio bytes to transcribe.
            language_code: BCP-47 language code. Defaults to client language.
            encoding: Audio encoding of the content.
            sample_rate_hertz: Audio sample rate.
            enable_word_time_offsets: Include per-word timing information.
            enable_automatic_punctuation: Add punctuation to transcript.
            speech_contexts: Optional list of phrases to boost recognition.

        Returns:
            TranscriptResult with transcribed text and confidence.

        Raises:
            google.api_core.exceptions.GoogleAPIError: On transcription failure.
        """
        lang = language_code or self.language_code

        encoding_map = {
            AudioEncodingEnum.LINEAR16: speech_v1.RecognitionConfig.AudioEncoding.LINEAR16,
            AudioEncodingEnum.MP3: speech_v1.RecognitionConfig.AudioEncoding.MP3,
            AudioEncodingEnum.OGG_OPUS: speech_v1.RecognitionConfig.AudioEncoding.OGG_OPUS,
            AudioEncodingEnum.MULAW: speech_v1.RecognitionConfig.AudioEncoding.MULAW,
        }
        rec_encoding = encoding_map.get(encoding, speech_v1.RecognitionConfig.AudioEncoding.MP3)

        contexts = []
        if speech_contexts:
            contexts = [SpeechContext(phrases=speech_contexts)]

        config = RecognitionConfig(
            encoding=rec_encoding,
            sample_rate_hertz=sample_rate_hertz,
            language_code=lang,
            enable_word_time_offsets=enable_word_time_offsets,
            enable_automatic_punctuation=enable_automatic_punctuation,
            speech_contexts=contexts,
        )

        audio = RecognitionAudio(content=audio_content)

        response = self.client.recognize(config=config, audio=audio)

        if not response.results:
            return TranscriptResult(
                transcript_text="",
                confidence=0.0,
                language_code=lang,
            )

        best_result = response.results[0]
        transcript = best_result.alternatives[0].transcript
        confidence = best_result.alternatives[0].confidence
        words = list(best_result.alternatives[0].words) if enable_word_time_offsets else []

        return TranscriptResult(
            transcript_text=transcript,
            confidence=confidence,
            words=words,
            language_code=lang,
        )

    def verify_synthesis(
        self,
        original_text: str,
        audio_content: bytes,
        language_code: Optional[str] = None,
        encoding: AudioEncodingEnum = AudioEncodingEnum.MP3,
        sample_rate_hertz: int = 24000,
        acceptance_threshold: float = 0.7,
        speech_contexts: Optional[List[str]] = None,
    ) -> QAVerificationResult:
        """
        Verify TTS synthesis quality by transcribing and comparing to original text.

        Provider: Google Cloud Speech-to-Text via google-cloud-speech SDK.
        API endpoint: speech.googleapis.com

        Args:
            original_text: The text that was synthesized.
            audio_content: Audio bytes from TTS synthesis.
            language_code: Language code for transcription.
            encoding: Audio encoding format.
            sample_rate_hertz: Audio sample rate.
            acceptance_threshold: Minimum match score to pass QA (0.0-1.0).
            speech_contexts: Optional phrases to boost speech recognition.

        Returns:
            QAVerificationResult with match analysis.
        """
        transcript = self.transcribe_audio(
            audio_content=audio_content,
            language_code=language_code,
            encoding=encoding,
            sample_rate_hertz=sample_rate_hertz,
            speech_contexts=speech_contexts,
        )

        return self._compare_texts(original_text, transcript, acceptance_threshold)

    def _compare_texts(
        self,
        original: str,
        transcript: TranscriptResult,
        threshold: float,
    ) -> QAVerificationResult:
        """
        Compare original text with transcribed text to compute match metrics.
        """
        original_words = _normalize_words(original)
        transcript_words = _normalize_words(transcript.transcript_text)

        original_set = set(original_words)
        transcript_set = set(transcript_words)

        matching = original_set & transcript_set
        missing = original_set - transcript_set
        extra = transcript_set - original_set

        if len(original_set) == 0:
            match_score = 1.0 if len(transcript_set) == 0 else 0.0
        else:
            match_score = len(matching) / len(original_set)

        word_errors = list(missing | extra)

        return QAVerificationResult(
            original_text=original,
            transcript_text=transcript.transcript_text,
            match_score=round(match_score, 3),
            is_acceptable=match_score >= threshold,
            confidence=transcript.confidence,
            word_errors=list(word_errors),
            missing_words=list(missing),
            extra_words=list(extra),
        )


def _normalize_words(text: str) -> List[str]:
    """Normalize text into a list of lowercase words for comparison."""
    import re

    cleaned = text.lower().strip()
    cleaned = re.sub(r"[^\w\s]", "", cleaned)
    words = cleaned.split()
    return words


def transcribe_tts_sample(
    audio_content: bytes,
    language_code: str = "en-US",
    encoding: AudioEncodingEnum = AudioEncodingEnum.MP3,
    sample_rate_hertz: int = 24000,
    credentials_path: Optional[str] = None,
) -> TranscriptResult:
    """
    Transcribe a TTS-generated audio sample using Google Cloud Speech-to-Text.

    Provider: Google Cloud Speech-to-Text via google-cloud-speech SDK.
    API endpoint: speech.googleapis.com

    Args:
        audio_content: Raw audio bytes from TTS.
        language_code: BCP-47 language code.
        encoding: Audio encoding format.
        sample_rate_hertz: Audio sample rate.
        credentials_path: Path to Google service account JSON.

    Returns:
        TranscriptResult with transcribed text and confidence.
    """
    transcriber = TTSQATranscriber(
        language_code=language_code,
        credentials_path=credentials_path,
    )
    return transcriber.transcribe_audio(
        audio_content=audio_content,
        language_code=language_code,
        encoding=encoding,
        sample_rate_hertz=sample_rate_hertz,
    )


def verify_tts_quality(
    original_text: str,
    audio_content: bytes,
    language_code: str = "en-US",
    encoding: AudioEncodingEnum = AudioEncodingEnum.MP3,
    sample_rate_hertz: int = 24000,
    acceptance_threshold: float = 0.7,
    credentials_path: Optional[str] = None,
) -> QAVerificationResult:
    """
    Perform end-to-end QA verification of TTS synthesis.

    Transcribes the synthesized audio and compares it against the original
    input text to verify that the TTS output accurately speaks the intended words.

    Provider: Google Cloud Speech-to-Text via google-cloud-speech SDK.
    API endpoint: speech.googleapis.com

    Args:
        original_text: Text that was synthesized.
        audio_content: Audio bytes from TTS synthesis.
        language_code: BCP-47 language code.
        encoding: Audio encoding format.
        sample_rate_hertz: Audio sample rate.
        acceptance_threshold: Minimum match score for QA pass.
        credentials_path: Path to Google service account JSON.

    Returns:
        QAVerificationResult with quality assessment.
    """
    transcriber = TTSQATranscriber(
        language_code=language_code,
        credentials_path=credentials_path,
    )
    return transcriber.verify_synthesis(
        original_text=original_text,
        audio_content=audio_content,
        language_code=language_code,
        encoding=encoding,
        sample_rate_hertz=sample_rate_hertz,
        acceptance_threshold=acceptance_threshold,
    )



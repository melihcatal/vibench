"""
Check prompts and generated text for unsafe content.

Provider: Azure AI Content Safety
SDK: requests (REST interface to Azure Content Safety API)
Auth: AZURE_CONTENT_SAFETY_ENDPOINT, AZURE_CONTENT_SAFETY_KEY
Endpoint: {AZURE_CONTENT_SAFETY_ENDPOINT}/contentsafety/text:analyze?api-version=2024-02-15-preview
"""

import os
from typing import Any, Dict, List, Optional

import requests

AZURE_CONTENT_SAFETY_API_VERSION = "2024-02-15-preview"

CONTENT_SAFETY_CATEGORIES = [
    "Hate",
    "SelfHarm",
    "Sexual",
    "Violence",
]


def _resolve_azure_safety_config() -> Dict[str, str]:
    """Resolve Azure AI Content Safety configuration from environment variables."""
    endpoint = os.environ.get("AZURE_CONTENT_SAFETY_ENDPOINT")
    key = os.environ.get("AZURE_CONTENT_SAFETY_KEY")
    if not endpoint or not key:
        raise EnvironmentError(
            "AZURE_CONTENT_SAFETY_ENDPOINT and AZURE_CONTENT_SAFETY_KEY "
            "are required for Azure AI Content Safety integration"
        )
    # Ensure endpoint has no trailing slash
    endpoint = endpoint.rstrip("/")
    return {"endpoint": endpoint, "key": key}


def check_text_safety(
    text: str,
    categories: Optional[List[str]] = None,
    block_threshold: int = 4,
) -> Dict[str, Any]:
    """
    Analyze text for unsafe content using Azure AI Content Safety.

    Provider: Azure AI Content Safety
    Endpoint: {endpoint}/contentsafety/text:analyze?api-version=2024-02-15-preview
    Categories: Hate, SelfHarm, Sexual, Violence
    Severity levels: 0-7 (0=none, 2=safe, 4=medium, 6=high)

    Args:
        text: The text to analyze for safety.
        categories: List of categories to check. Defaults to all four.
        block_threshold: Severity threshold above which content is flagged
                         (default: 4 = medium severity).

    Returns:
        Dictionary with analysis results including per-category scores
        and an overall 'safe' boolean flag.
    """
    config = _resolve_azure_safety_config()
    url = (
        f"{config['endpoint']}/contentsafety/text:analyze"
        f"?api-version={AZURE_CONTENT_SAFETY_API_VERSION}"
    )

    headers = {
        "Ocp-Apim-Subscription-Key": config["key"],
        "Content-Type": "application/json",
    }

    check_categories = categories or CONTENT_SAFETY_CATEGORIES
    categories_payload = [{"category": cat} for cat in check_categories]

    payload = {
        "text": text,
        "categories": categories_payload,
        "outputType": "EightSeverityLevels",
    }

    response = requests.post(url, headers=headers, json=payload)
    response.raise_for_status()
    data = response.json()

    category_results = {}
    is_safe = True

    for category_analysis in data.get("categoriesAnalysis", []):
        cat_name = category_analysis.get("category", "Unknown")
        severity = category_analysis.get("severity", 0)
        flagged = severity >= block_threshold
        category_results[cat_name] = {
            "severity": severity,
            "flagged": flagged,
            "threshold": block_threshold,
        }
        if flagged:
            is_safe = False

    return {
        "safe": is_safe,
        "categories": category_results,
        "block_threshold": block_threshold,
        "raw_response": data,
    }


def check_prompt_safety(prompt: str, block_threshold: int = 4) -> Dict[str, Any]:
    """
    Check a user prompt for unsafe content before sending to an LLM.

    Provider: Azure AI Content Safety

    Args:
        prompt: The user prompt to validate.
        block_threshold: Severity threshold (default: 4).

    Returns:
        Safety analysis result dictionary.
    """
    return check_text_safety(
        text=prompt,
        block_threshold=block_threshold,
    )


def check_generated_text_safety(
    generated_text: str,
    block_threshold: int = 4,
) -> Dict[str, Any]:
    """
    Check generated LLM output text for unsafe content.

    Provider: Azure AI Content Safety

    Args:
        generated_text: The text generated by the LLM.
        block_threshold: Severity threshold (default: 4).

    Returns:
        Safety analysis result dictionary.
    """
    return check_text_safety(
        text=generated_text,
        block_threshold=block_threshold,
    )

"""
Stream partial output tokens from a hosted LLM.

Provider: OpenAI Chat Completions API (streaming)
SDK: openai
Auth: OPENAI_API_KEY
Concrete model: gpt-4o
Endpoint: api.openai.com/v1/chat/completions?stream=true
"""

from typing import Iterator, Optional

from model_client import call_llm_stream
from model_models import LLMRequest


def stream_completion(
    prompt: str,
    system_prompt: Optional[str] = None,
    model_name: Optional[str] = None,
    temperature: float = 0.7,
    max_tokens: int = 2048,
) -> Iterator[str]:
    """
    Stream partial output tokens from the OpenAI gpt-4o model.

    Args:
        prompt: The user prompt to send to the model.
        system_prompt: Optional system prompt.
        model_name: Optional model override (default: gpt-4o).
        temperature: Sampling temperature.
        max_tokens: Maximum number of tokens to generate.

    Yields:
        Partial text chunks as they are generated by OpenAI.
    """
    effective_model = model_name or "gpt-4o"
    request = LLMRequest(
        user_prompt=prompt,
        system_prompt=system_prompt or "You are a helpful assistant.",
        model_name=effective_model,
        temperature=temperature,
        max_tokens=max_tokens,
    )

    yield from call_llm_stream(request)


def stream_completion_full(
    prompt: str,
    system_prompt: Optional[str] = None,
    model_name: Optional[str] = None,
    temperature: float = 0.7,
    max_tokens: int = 2048,
) -> str:
    """
    Stream tokens from OpenAI gpt-4o and concatenate into a full response.

    Args:
        prompt: The user prompt.
        system_prompt: Optional system prompt.
        model_name: Optional model override.
        temperature: Sampling temperature.
        max_tokens: Maximum tokens to generate.

    Returns:
        The complete streamed response as a single string.
    """
    collected = []
    for chunk in stream_completion(
        prompt=prompt,
        system_prompt=system_prompt,
        model_name=model_name,
        temperature=temperature,
        max_tokens=max_tokens,
    ):
        collected.append(chunk)
    return "".join(collected)

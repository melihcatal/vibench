"""Translate platform model output for another locale using the OpenAI chat completions API.

Uses the openai.OpenAI client with the gpt-4o model to translate text
generated by the platform into a target locale.
"""

from __future__ import annotations

from typing import Optional

from openai import OpenAI

from model_client import create_openai_client, with_retry
from model_models import PlatformModelRequest, PlatformModelResponse

OPENAI_TRANSLATION_MODEL = "gpt-4o"

SYSTEM_PROMPT_TEMPLATE = (
    "You are a professional translator. Translate the following text into "
    "{locale}. Preserve formatting, tone, and any technical terminology "
    "where appropriate. Return only the translated text, with no preamble "
    "or explanation."
)


def localized_platform_output(
    text: str,
    target_locale: str,
    client: Optional[OpenAI] = None,
    model: str = OPENAI_TRANSLATION_MODEL,
) -> str:
    """Translate platform model output into the specified locale via OpenAI.

    Args:
        text: The source text generated by the platform.
        target_locale: Target locale code (e.g., "es-ES", "ja", "fr-FR").
        client: Optional pre-configured OpenAI client.
        model: The OpenAI model to use for translation.

    Returns:
        The translated text as a string.
    """
    resolved_client = client or create_openai_client()
    system_prompt = SYSTEM_PROMPT_TEMPLATE.format(locale=target_locale)

    request = PlatformModelRequest(
        model_id=model,
        messages=[
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": text},
        ],
        temperature=0.3,
        max_tokens=4096,
        stream=False,
    )
    payload = request.to_openai_payload()

    def _call():
        return resolved_client.chat.completions.create(**payload)

    completion = with_retry(_call)
    translated = completion.choices[0].message.content
    return translated if translated else ""


def localized_platform_output_with_fallback(
    text: str,
    target_locale: str,
    client: Optional[OpenAI] = None,
    primary_model: str = OPENAI_TRANSLATION_MODEL,
    fallback_model: str = "gpt-4o-mini",
) -> str:
    """Translate with a fallback model if the primary fails.

    Attempts translation with the primary OpenAI model; if an error occurs,
    retries with the fallback model.
    """
    try:
        return localized_platform_output(text, target_locale, client, primary_model)
    except Exception:
        return localized_platform_output(text, target_locale, client, fallback_model)

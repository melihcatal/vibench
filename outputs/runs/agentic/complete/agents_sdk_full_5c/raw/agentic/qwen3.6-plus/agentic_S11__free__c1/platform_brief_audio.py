"""Generate spoken briefings from platform outputs using the OpenAI Audio (TTS) API.

Uses the openai.OpenAI client with the tts-1 model to synthesize speech
from text generated by the managed model platform, returning raw audio bytes.
"""

from __future__ import annotations

import os
from typing import Optional

from openai import OpenAI

from model_client import create_openai_client, with_retry
from model_models import PlatformModelRequest, PlatformModelResponse

OPENAI_TTS_MODEL = "tts-1"
OPENAI_TTS_MODEL_HD = "tts-1-hd"


def platform_brief_audio(
    text: str,
    client: Optional[OpenAI] = None,
    model: str = OPENAI_TTS_MODEL,
    voice: str = "alloy",
    response_format: str = "mp3",
    speed: float = 1.0,
) -> bytes:
    """Generate a spoken audio briefing from platform output via OpenAI TTS.

    Args:
        text: The text content to synthesize as speech.
        client: Optional pre-configured OpenAI client.
        model: The OpenAI TTS model identifier (tts-1 or tts-1-hd).
        voice: OpenAI voice name (alloy, echo, fable, onyx, nova, shimmer).
        response_format: Audio format (mp3, opus, aac, flac, wav, pcm).
        speed: Speech speed multiplier (0.25 to 4.0).

    Returns:
        Raw audio bytes in the requested format.
    """
    resolved_client = client or create_openai_client()

    def _call():
        return resolved_client.audio.speech.create(
            model=model,
            voice=voice,
            input=text,
            response_format=response_format,
            speed=speed,
        )

    speech_response = with_retry(_call)
    return speech_response.content


def platform_brief_audio_to_file(
    text: str,
    output_path: str,
    client: Optional[OpenAI] = None,
    model: str = OPENAI_TTS_MODEL,
    voice: str = "alloy",
    response_format: str = "mp3",
    speed: float = 1.0,
) -> str:
    """Generate audio and write it to a local file.

    Returns the absolute path to the written audio file.
    """
    audio_bytes = platform_brief_audio(
        text, client, model, voice, response_format, speed
    )
    abs_path = os.path.abspath(output_path)
    with open(abs_path, "wb") as f:
        f.write(audio_bytes)
    return abs_path


def generate_briefing_summary_and_audio(
    platform_text: str,
    client: Optional[OpenAI] = None,
    summary_model: str = "gpt-4o",
    tts_model: str = OPENAI_TTS_MODEL,
    voice: str = "alloy",
) -> tuple:
    """Summarize platform output via gpt-4o, then produce audio via OpenAI TTS.

    Returns (summary_text, audio_bytes).
    """
    resolved_client = client or create_openai_client()

    # Step 1: Summarize using gpt-4o
    summary_request = PlatformModelRequest(
        model_id=summary_model,
        messages=[
            {
                "role": "system",
                "content": (
                    "You are a briefing assistant. Condense the following text "
                    "into a concise spoken briefing of 3-5 sentences suitable "
                    "for text-to-speech synthesis."
                ),
            },
            {"role": "user", "content": platform_text},
        ],
        temperature=0.3,
        max_tokens=256,
    )
    payload = summary_request.to_openai_payload()

    def _summarize():
        return resolved_client.chat.completions.create(**payload)

    summary_completion = with_retry(_summarize)
    summary_response = PlatformModelResponse.from_openai_completion(summary_completion)
    summary_text = summary_response.content

    # Step 2: Synthesize audio using OpenAI tts-1
    audio_bytes = platform_brief_audio(
        summary_text,
        client=resolved_client,
        model=tts_model,
        voice=voice,
    )

    return summary_text, audio_bytes

"""Check platform model output for unsafe content using the OpenAI Moderations API.

Uses the openai.Moderations.create endpoint with the omni-moderation-latest
model to evaluate text generated by the OpenAI platform for policy violations.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple

from openai import OpenAI
from openai.types import ModerationCreateResponse

from model_client import create_openai_client, with_retry

OPENAI_MODERATION_MODEL = "omni-moderation-latest"


def check_platform_output_safety(
    text: str,
    client: Optional[OpenAI] = None,
    model: str = OPENAI_MODERATION_MODEL,
) -> Dict[str, Any]:
    """Evaluate text for unsafe content via the OpenAI Moderations API.

    Args:
        text: The model output text to evaluate.
        client: Optional pre-configured OpenAI client.
        model: The OpenAI moderation model identifier.

    Returns:
        A dict with keys:
          - flagged (bool): Whether any moderation category was triggered.
          - categories (dict): Per-category boolean flags.
          - category_scores (dict): Per-category confidence scores.
          - raw_response: The raw OpenAI ModerationCreateResponse.
    """
    resolved_client = client or create_openai_client()

    def _call() -> ModerationCreateResponse:
        return resolved_client.moderations.create(input=text, model=model)

    moderation_resp: ModerationCreateResponse = with_retry(_call)
    result = moderation_resp.results[0]

    return {
        "flagged": result.flagged,
        "categories": dict(result.categories),
        "category_scores": dict(result.category_scores),
        "model": moderation_resp.model,
        "raw_response": moderation_resp,
    }


def check_platform_output_safety_batch(
    texts: List[str],
    client: Optional[OpenAI] = None,
    model: str = OPENAI_MODERATION_MODEL,
) -> List[Dict[str, Any]]:
    """Evaluate multiple texts for unsafe content via OpenAI Moderations API.

    Returns a list of safety check dicts, one per input text.
    """
    resolved_client = client or create_openai_client()

    def _call() -> ModerationCreateResponse:
        return resolved_client.moderations.create(input=texts, model=model)

    moderation_resp: ModerationCreateResponse = with_retry(_call)
    results = []
    for result in moderation_resp.results:
        results.append({
            "flagged": result.flagged,
            "categories": dict(result.categories),
            "category_scores": dict(result.category_scores),
        })
    return results


def is_output_safe(
    text: str,
    client: Optional[OpenAI] = None,
    model: str = OPENAI_MODERATION_MODEL,
) -> Tuple[bool, Dict[str, float]]:
    """Return (is_safe, category_scores) for quick safety gating."""
    safety = check_platform_output_safety(text, client, model)
    return not safety["flagged"], safety["category_scores"]

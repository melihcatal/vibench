"""Translate platform model output for another locale using the DeepL API.

Uses the DeepL translation API to translate text generated by a
managed model platform into a target locale, preserving the original
content while adapting language and cultural context.
"""

from typing import Dict, Any, Optional, List

import deepl

from model_models import LocalizationResult


DEEPL_API_HOST = "api-free.deepl.com"


def get_deepl_client(provider_config: Optional[Dict[str, Any]] = None):
    """Create and return a DeepL SDK client.

    Args:
        provider_config: Optional configuration with DEEPL_API_KEY.

    Returns:
        Configured DeepL Translator instance.
    """
    if provider_config is None:
        provider_config = {}

    api_key = provider_config.get(
        "deepl_api_key",
        __import__("os").environ.get("DEEPL_API_KEY", ""),
    )

    return deepl.Translator(api_key)


def translate_platform_output(
    text: str,
    target_lang: str = "ES",
    source_lang: Optional[str] = None,
    provider_config: Optional[Dict[str, Any]] = None,
) -> LocalizationResult:
    """Translate platform model output to a target locale using DeepL.

    Uses the DeepL translation API to convert generated text into
    the specified target language.

    Args:
        text: The text output to translate.
        target_lang: Target language code (e.g., "ES", "FR", "DE", "JA").
        source_lang: Optional source language code.
        provider_config: Optional pre-loaded DeepL configuration.

    Returns:
        LocalizationResult with translated text and metadata.
    """
    translator = get_deepl_client(provider_config)

    translate_kwargs: Dict[str, Any] = {
        "target_lang": target_lang,
    }

    if source_lang:
        translate_kwargs["source_lang"] = source_lang

    result = translator.translate_text(text, **translate_kwargs)

    return LocalizationResult(
        original_text=text,
        translated_text=result.text,
        source_locale=result.detected_source_lang or source_lang or "en",
        target_locale=target_lang.lower(),
        provider="deepl",
    )


def translate_batch_outputs(
    texts: List[str],
    target_lang: str = "ES",
    source_lang: Optional[str] = None,
    provider_config: Optional[Dict[str, Any]] = None,
) -> List[LocalizationResult]:
    """Translate multiple platform outputs in a single batch.

    Args:
        texts: List of texts to translate.
        target_lang: Target language code.
        source_lang: Optional source language code.
        provider_config: Optional pre-loaded configuration.

    Returns:
        List of LocalizationResult objects.
    """
    translator = get_deepl_client(provider_config)

    translate_kwargs: Dict[str, Any] = {
        "target_lang": target_lang,
    }

    if source_lang:
        translate_kwargs["source_lang"] = source_lang

    results = translator.translate_text(texts, **translate_kwargs)

    localization_results = []
    for i, result in enumerate(results):
        localization_results.append(
            LocalizationResult(
                original_text=texts[i],
                translated_text=result.text,
                source_locale=result.detected_source_lang or source_lang or "en",
                target_locale=target_lang.lower(),
                provider="deepl",
            )
        )

    return localization_results


def detect_and_translate(
    text: str,
    target_lang: str = "JA",
    provider_config: Optional[Dict[str, Any]] = None,
) -> LocalizationResult:
    """Auto-detect source language and translate platform output.

    Args:
        text: The text output to translate.
        target_lang: Target language code.
        provider_config: Optional pre-loaded configuration.

    Returns:
        LocalizationResult with detected source and translated text.
    """
    translator = get_deepl_client(provider_config)

    result = translator.translate_text(text, target_lang=target_lang)

    return LocalizationResult(
        original_text=text,
        translated_text=result.text,
        source_locale=result.detected_source_lang or "en",
        target_locale=target_lang.lower(),
        provider="deepl",
    )


def get_supported_languages(
    provider_config: Optional[Dict[str, Any]] = None,
) -> List[Dict[str, str]]:
    """Get list of supported target languages from DeepL.

    Args:
        provider_config: Optional pre-loaded configuration.

    Returns:
        List of language dictionaries with code and name.
    """
    translator = get_deepl_client(provider_config)

    languages = translator.get_target_languages()

    return [
        {"code": lang.code, "name": lang.name, "supports_formality": getattr(lang, "supports_formality", False)}
        for lang in languages
    ]


def translate_with_formality(
    text: str,
    target_lang: str = "DE",
    formal: bool = True,
    provider_config: Optional[Dict[str, Any]] = None,
) -> LocalizationResult:
    """Translate with formality preference for languages that support it.

    Args:
        text: The text to translate.
        target_lang: Target language code (e.g., "DE", "FR", "ES", "IT", "JA").
        formal: Whether to use formal or informal register.
        provider_config: Optional pre-loaded configuration.

    Returns:
        LocalizationResult with formality-aware translation.
    """
    translator = get_deepl_client(provider_config)

    result = translator.translate_text(
        text,
        target_lang=target_lang,
        formality="preferMore" if formal else "preferLess",
    )

    return LocalizationResult(
        original_text=text,
        translated_text=result.text,
        source_locale=result.detected_source_lang or "en",
        target_locale=target_lang.lower(),
        provider="deepl",
    )

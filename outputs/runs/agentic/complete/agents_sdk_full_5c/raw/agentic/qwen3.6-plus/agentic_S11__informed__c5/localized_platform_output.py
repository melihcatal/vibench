"""Translate platform model output for another locale using Amazon Translate."""

from typing import Optional, List, Dict, Any

from model_client import (
    load_aws_credentials,
    create_translate_client,
)
from model_models import TranslationResult


def translate_platform_output(
    text: str,
    target_language: str = "es",
    source_language: Optional[str] = None,
    region: str = "us-east-1",
) -> TranslationResult:
    """Translate model output text using Amazon Translate.

    Uses the boto3 translate client to call the TranslateText API
    on Amazon Translate service for translating text generated by
    platform models (e.g., from Amazon Bedrock) into another locale.

    Amazon Translate endpoint: translate.{region}.amazonaws.com
    """
    credentials, aws_region = load_aws_credentials()
    effective_region = region or aws_region

    client = create_translate_client(credentials=credentials, region=effective_region)

    translate_kwargs: Dict[str, Any] = {
        "Text": text,
        "TargetLanguageCode": target_language,
    }
    if source_language:
        translate_kwargs["SourceLanguageCode"] = source_language

    response = client.translate_text(**translate_kwargs)

    translated = response.get("TranslatedText", "")
    detected_source = response.get("SourceLanguageCode", source_language or "auto")

    return TranslationResult(
        original_text=text,
        translated_text=translated,
        source_language=detected_source,
        target_language=target_language,
        model_id=response.get("Settings", {}).get("Brevity", "standard"),
    )


def batch_translate_platform_outputs(
    texts: List[str],
    target_language: str = "fr",
    source_language: Optional[str] = None,
    region: str = "us-east-1",
) -> List[TranslationResult]:
    """Batch translate multiple platform model outputs on Amazon Translate.

    Uses Amazon Translate to translate a list of texts. Each text may be
    the output from a Bedrock model invocation.
    """
    credentials, aws_region = load_aws_credentials()
    effective_region = region or aws_region

    client = create_translate_client(credentials=credentials, region=effective_region)

    results: List[TranslationResult] = []

    for text in texts:
        translate_kwargs: Dict[str, Any] = {
            "Text": text,
            "TargetLanguageCode": target_language,
        }
        if source_language:
            translate_kwargs["SourceLanguageCode"] = source_language

        response = client.translate_text(**translate_kwargs)

        results.append(TranslationResult(
            original_text=text,
            translated_text=response.get("TranslatedText", ""),
            source_language=response.get("SourceLanguageCode", source_language or "auto"),
            target_language=target_language,
            model_id="amazon-translate",
        ))

    return results


def translate_with_custom_terminology(
    text: str,
    target_language: str = "ja",
    source_language: str = "en",
    terminology_names: Optional[List[str]] = None,
    region: str = "us-east-1",
) -> TranslationResult:
    """Translate using Amazon Translate with custom terminology.

    Uses the boto3 translate client with TerminologyNames to apply
    domain-specific terminology during translation of platform model output.
    """
    credentials, aws_region = load_aws_credentials()
    effective_region = region or aws_region

    client = create_translate_client(credentials=credentials, region=effective_region)

    translate_kwargs: Dict[str, Any] = {
        "Text": text,
        "TargetLanguageCode": target_language,
        "SourceLanguageCode": source_language,
    }
    if terminology_names:
        translate_kwargs["TerminologyNames"] = terminology_names

    response = client.translate_text(**translate_kwargs)

    return TranslationResult(
        original_text=text,
        translated_text=response.get("TranslatedText", ""),
        source_language=source_language,
        target_language=target_language,
        model_id="amazon-translate",
    )

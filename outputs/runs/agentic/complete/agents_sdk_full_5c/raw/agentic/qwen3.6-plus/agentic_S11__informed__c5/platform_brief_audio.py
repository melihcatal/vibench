"""Generate spoken briefings from platform outputs using Amazon Polly."""

from typing import Optional, Dict, Any

from model_client import (
    load_aws_credentials,
    create_polly_client,
)
from model_models import SpeechResult


def generate_brief_audio(
    text: str,
    voice_id: str = "Joanna",
    engine: str = "neural",
    output_format: str = "mp3",
    sample_rate: str = "24000",
    region: str = "us-east-1",
) -> SpeechResult:
    """Generate a spoken audio briefing from platform model output using Amazon Polly.

    Uses the boto3 polly client to call the SynthesizeSpeech API
    on Amazon Polly, converting text generated by platform models
    (e.g., from Amazon Bedrock) into natural-sounding speech.

    Amazon Polly endpoint: polly.{region}.amazonaws.com
    """
    credentials, aws_region = load_aws_credentials()
    effective_region = region or aws_region

    client = create_polly_client(credentials=credentials, region=effective_region)

    polly_kwargs: Dict[str, Any] = {
        "Text": text,
        "VoiceId": voice_id,
        "Engine": engine,
        "OutputFormat": output_format,
    }

    if output_format == "mp3":
        polly_kwargs["SampleRate"] = sample_rate

    response = client.synthesize_speech(**polly_kwargs)

    audio_stream = response.get("AudioStream")
    audio_content = audio_stream.read() if audio_stream else b""

    content_type = response.get("ContentType", f"audio/{output_format}")

    return SpeechResult(
        text=text,
        audio_content=audio_content,
        voice_id=voice_id,
        audio_format=output_format,
        sample_rate=int(sample_rate) if sample_rate.isdigit() else 24000,
    )



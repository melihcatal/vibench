"""Check platform model output for unsafe content using Amazon Comprehend."""

from typing import List, Dict, Any

from model_client import (
    load_aws_credentials,
    create_comprehend_client,
)
from model_models import SafetyCheckResult


def check_bedrock_output_safety(
    text: str,
    region: str = "us-east-1",
) -> SafetyCheckResult:
    """Check model output text for unsafe content using Amazon Comprehend.

    Uses the boto3 comprehend client to call DetectToxicContent API
    on Amazon Comprehend to detect toxicity in text generated by
    models on Amazon Bedrock.

    Amazon Comprehend endpoint: comprehend.{region}.amazonaws.com
    """
    credentials, aws_region = load_aws_credentials()
    effective_region = region or aws_region

    client = create_comprehend_client(credentials=credentials, region=effective_region)

    response = client.detect_toxic_content(
        TextSegments=[{"Text": text}],
        LanguageCode="en",
    )

    result_segments = response.get("ResultList", [])
    labels: Dict[str, float] = {}
    confidence_scores: Dict[str, float] = {}
    flagged_categories: List[str] = []
    is_safe = True

    for segment_result in result_segments:
        toxic_labels = segment_result.get("Labels", [])
        for label_entry in toxic_labels:
            name = label_entry.get("Name", "")
            score = label_entry.get("Score", 0.0)
            labels[name] = score
            confidence_scores[name] = score

            if score >= 0.5:
                flagged_categories.append(name)
                is_safe = False

    request_id = response.get("ResponseMetadata", {}).get("RequestId", "")

    return SafetyCheckResult(
        text=text,
        is_safe=is_safe,
        labels=labels,
        confidence_scores=confidence_scores,
        flagged_categories=flagged_categories,
        request_id=request_id,
    )



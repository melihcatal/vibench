import os
import json
from typing import Dict, Any
import google.generativeai as genai


def summarize_invoice_fields(invoice_data: Dict[str, Any]) -> str:
    """
    Summarize extracted invoice fields using Google Gemini API.

    Args:
        invoice_data: Extracted invoice data from document extraction

    Returns:
        Summary of invoice fields
    """
    # Configure Gemini API
    api_key = os.getenv("GOOGLE_API_KEY")
    if not api_key:
        raise ValueError("GOOGLE_API_KEY environment variable is required")

    genai.configure(api_key=api_key)

    # Prepare prompt with invoice data
    invoice_json = json.dumps(invoice_data, indent=2)
    prompt = f"""Summarize this invoice extraction data in a clear, concise paragraph.
Focus on the key details: vendor, date, total amount, and number of line items.

Invoice Data:
{invoice_json}

Provide a brief summary that highlights:
1. Who the invoice is from (vendor)
2. When it was issued (date)
3. The total amount
4. How many line items there are
5. Any notable items or amounts

Summary:"""

    try:
        # Call Gemini API with gemini-1.5-pro model
        model = genai.GenerativeModel("gemini-1.5-pro")
        response = model.generate_content(prompt)

        summary = response.text.strip()

        # Add metadata about the provider
        summary_with_metadata = (
            f"{summary}\n\n[Generated by Google Gemini API using gemini-1.5-pro model]"
        )

        return summary_with_metadata

    except Exception as e:
        raise Exception(f"Gemini API error: {e}")

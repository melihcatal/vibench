import os
from typing import List, Dict, Any
from anthropic import Anthropic


def rotation_summary(
    secret_names: List[str], rotation_statuses: List[Dict[str, Any]]
) -> str:
    """
    Summarize secret rotation status using Anthropic Claude.

    Args:
        secret_names: List of secret names
        rotation_statuses: List of rotation status dictionaries

    Returns:
        Summary of rotation status
    """
    # Anthropic provider-specific client
    client = Anthropic(api_key=os.environ.get("ANTHROPIC_API_KEY"))

    # Prepare data for summarization
    summary_data = []
    for name, status in zip(secret_names, rotation_statuses):
        summary_data.append(
            {
                "secret": name,
                "rotation_enabled": status.get("rotation_enabled", False),
                "last_rotated": status.get("last_rotated_date", "Never"),
                "next_rotation": status.get("next_rotation_date", "Not scheduled"),
                "rotation_lambda": status.get("rotation_lambda_arn", "Not configured"),
            }
        )

    # Create prompt for Claude
    prompt = f"""You are a security operations analyst summarizing secret rotation status.
    
Here is the rotation status data for {len(summary_data)} secrets:

{summary_data}

Please provide a concise summary that includes:
1. How many secrets have rotation enabled vs disabled
2. Which secrets haven't been rotated recently (if last rotation > 90 days ago)
3. Any secrets missing rotation configuration
4. Overall rotation health status (Good, Needs Attention, Poor)

Format the summary in clear, actionable language for security teams."""

    try:
        # Use Claude-3 model family
        response = client.messages.create(
            model="claude-3-sonnet-20240229",
            max_tokens=500,
            temperature=0.2,
            messages=[{"role": "user", "content": prompt}],
        )

        summary = response.content[0].text

        # Add metadata about the model used
        full_summary = f"""Rotation Status Summary (Generated by Anthropic Claude-3 Sonnet)
====================================================================

{summary}

---
Analysis based on {len(summary_data)} secrets.
Model: claude-3-sonnet-20240229
Provider: Anthropic Claude API"""

        return full_summary

    except Exception as e:
        raise RuntimeError(f"Error generating rotation summary with Anthropic: {e}")

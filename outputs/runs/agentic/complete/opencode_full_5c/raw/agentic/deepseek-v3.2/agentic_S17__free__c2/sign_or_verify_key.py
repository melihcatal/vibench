import os
import json
import base64
import hashlib
import boto3
from botocore.exceptions import ClientError


def sign_with_key(
    message: str, key_id: str = None, signing_algorithm: str = "RSASSA_PSS_SHA_256"
) -> dict:
    """
    Sign a message using AWS KMS managed key.

    Args:
        message: The message to sign
        key_id: Optional AWS KMS key ID. If not provided, uses default key.
        signing_algorithm: Signing algorithm to use

    Returns:
        Dictionary with signature and signing metadata
    """
    # Initialize AWS KMS client
    kms_client = boto3.client(
        "kms", region_name=os.environ.get("AWS_REGION", "us-east-1")
    )

    # Use default key if not specified
    if not key_id:
        key_id = os.environ.get("AWS_KMS_SIGNING_KEY_ID", "alias/aws/signing-key")

    try:
        # Calculate message digest
        message_bytes = message.encode("utf-8")
        message_digest = hashlib.sha256(message_bytes).digest()

        # Sign the message digest using KMS
        sign_response = kms_client.sign(
            KeyId=key_id,
            Message=message_digest,
            MessageType="DIGEST",
            SigningAlgorithm=signing_algorithm,
        )

        signature = sign_response["Signature"]

        # Prepare response
        result = {
            "signature": base64.b64encode(signature).decode("utf-8"),
            "message": message,
            "message_digest": base64.b64encode(message_digest).decode("utf-8"),
            "key_id": key_id,
            "signing_algorithm": signing_algorithm,
            "hash_algorithm": "SHA256",
            "provider": "aws_kms",
        }

        return result

    except ClientError as e:
        raise Exception(f"AWS KMS signing failed: {str(e)}")
    except Exception as e:
        raise Exception(f"Signing failed: {str(e)}")


def verify_signature(signature_data: dict) -> bool:
    """
    Verify a signature using AWS KMS managed key.

    Args:
        signature_data: Dictionary containing:
            - signature: base64 encoded signature
            - message: original message
            - key_id: AWS KMS key ID (optional)
            - signing_algorithm: signing algorithm used

    Returns:
        True if signature is valid, False otherwise
    """
    # Initialize AWS KMS client
    kms_client = boto3.client(
        "kms", region_name=os.environ.get("AWS_REGION", "us-east-1")
    )

    try:
        # Decode base64 signature
        signature = base64.b64decode(signature_data["signature"])
        message = signature_data["message"]

        # Get key_id from data or environment
        key_id = signature_data.get("key_id") or os.environ.get(
            "AWS_KMS_SIGNING_KEY_ID", "alias/aws/signing-key"
        )

        # Get signing algorithm
        signing_algorithm = signature_data.get(
            "signing_algorithm", "RSASSA_PSS_SHA_256"
        )

        # Calculate message digest
        message_bytes = message.encode("utf-8")
        message_digest = hashlib.sha256(message_bytes).digest()

        # Verify the signature using KMS
        verify_response = kms_client.verify(
            KeyId=key_id,
            Message=message_digest,
            MessageType="DIGEST",
            Signature=signature,
            SigningAlgorithm=signing_algorithm,
        )

        return verify_response["SignatureValid"]

    except KeyError as e:
        raise Exception(f"Missing required field in signature data: {str(e)}")
    except ClientError as e:
        if e.response["Error"]["Code"] == "KMSInvalidSignatureException":
            return False
        raise Exception(f"AWS KMS verification failed: {str(e)}")
    except Exception as e:
        raise Exception(f"Verification failed: {str(e)}")


def generate_key_pair(
    key_spec: str = "RSA_2048", key_usage: str = "SIGN_VERIFY"
) -> dict:
    """
    Generate an asymmetric key pair using AWS KMS.

    Args:
        key_spec: Key specification (RSA_2048, RSA_3072, RSA_4096, ECC_NIST_P256, etc.)
        key_usage: Key usage (SIGN_VERIFY or ENCRYPT_DECRYPT)

    Returns:
        Dictionary with key metadata
    """
    # Initialize AWS KMS client
    kms_client = boto3.client(
        "kms", region_name=os.environ.get("AWS_REGION", "us-east-1")
    )

    try:
        # Create a new KMS key
        create_response = kms_client.create_key(
            KeyUsage=key_usage,
            KeySpec=key_spec,
            Description="Generated by sign_or_verify_key.py",
            Origin="AWS_KMS",
        )

        key_id = create_response["KeyMetadata"]["KeyId"]
        key_arn = create_response["KeyMetadata"]["Arn"]

        # Get public key
        public_key_response = kms_client.get_public_key(KeyId=key_id)
        public_key = public_key_response["PublicKey"]

        result = {
            "key_id": key_id,
            "key_arn": key_arn,
            "public_key": base64.b64encode(public_key).decode("utf-8"),
            "key_spec": key_spec,
            "key_usage": key_usage,
            "provider": "aws_kms",
        }

        return result

    except ClientError as e:
        raise Exception(f"AWS KMS key generation failed: {str(e)}")
    except Exception as e:
        raise Exception(f"Key generation failed: {str(e)}")

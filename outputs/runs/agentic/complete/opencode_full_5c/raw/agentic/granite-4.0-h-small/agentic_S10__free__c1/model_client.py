from typing import Any, Dict, List, TypeVar
import json
import os
from pydantic import BaseModel, Field

# ---------------------------------------------------------------------------
# Configuration Helpers
# ---------------------------------------------------------------------------
MODEL_API_KEY = os.getenv("MODEL_API_KEY")  # Replace with your provider's auth method
MODEL_ENDPOINT = os.getenv("MODEL_ENDPOINT", "https://api.openai.com/v1")
MODEL_DEFAULT = os.getenv("MODEL_DEFAULT", "gpt-4o-mini")

ALLOWED_MODELS = {
    "gpt-4o-mini",
    "gpt-4o",
    "gpt-3.5-turbo",
    # add more models supported by your provider here
}

# ---------------------------------------------------------------------------
# Pydantic response model for consistency
# ---------------------------------------------------------------------------
T = TypeVar("T")


class LLMResponse(BaseModel):
    id: str = Field(..., description="Request identifier generated by the provider")
    model: str = Field(..., description="Model used for the request")
    created: int = Field(..., description="Unix timestamp of generation")
    choices: List[Dict[str, Any]] = Field(..., description="Generated content/samples")

    class Config:
        allow_population_by_field_name = True
        arbitrary_types_allowed = True


# ---------------------------------------------------------------------------
# Client helper utilities
# ---------------------------------------------------------------------------
def create_client(model: str = MODEL_DEFAULT) -> Any:
    """Instantiate a client for the selected LLM provider.

    Args:
        model (str): Model family identifier (must be in ALLOWED_MODELS).

    Returns:
        An initialized client object (vendor-specific).  The caller can call
        `client.chat_completion(...)` following the provider's SDK style.
    """
    if model not in ALLOWED_MODELS:
        raise ValueError(
            f"Model {model!r} not supported. Choose from {', '.join(ALLOWED_MODELS)}"
        )

    # Example using OpenAI's official SDK (replace with your provider's SDK)
    # pip install openai
    from openai import OpenAI

    return OpenAI(api_key=MODEL_API_KEY, base_url=MODEL_ENDPOINT)


def _normalize_response(raw_resp: Any) -> LLMResponse:
    """Convert a raw provider response into our canonical LLMResponse.

    Args:
        raw_resp: The raw object returned by the provider's SDK.

    Returns:
        LLMResponse: Normalized representation.
    """
    return LLMResponse.parse_obj(raw_resp)

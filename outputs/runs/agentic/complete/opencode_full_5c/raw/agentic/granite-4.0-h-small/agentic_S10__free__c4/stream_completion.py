import asyncio
import json
import os
from model_client import HostedModelClient


def stream_completion(prefix: str, model: str = "gpt-4o") -> str:
    """Streams partial output tokens from a hosted LLM.

    Args:
        prefix: Initial text to start the completion from.
        model: Model identifier for the hosted LLM provider.

    Yields:
        Partial token strings as they are generated by the model.
    """
    client = HostedModelClient(model=model)
    payload = {"prompt": prefix, "temperature": 0.7, "stream": True}

    async def _stream():
        async for chunk in client.chat_completion_stream(payload):
            data = json.loads(chunk)
            content = data["choices"][0]["delta"].get("content", "")
            if content:
                yield content

    return asyncio.run(_stream())

# Generate a spoken briefing from platform model output using Amazon Polly TTS (via boto3)
import os
import json
import uuid
import boto3
from model_client import get_client, PROVIDER
from model_models import ModelResponse

POLLY_REGION = os.getenv("AWS_REGION", "us-east-1")
POLLY_VOICE_ID = os.getenv(
    "POLLY_VOICE_ID", "Joanna"
)  # default US English female voice


def text_to_speech(text: str, output_format: str = "mp3") -> bytes:
    """Synthesize speech from text using Amazon Polly and return raw audio bytes."""
    polly = boto3.client("polly", region_name=POLLY_REGION)
    resp = polly.synthesize_speech(
        Text=text, OutputFormat=output_format, VoiceId=POLLY_VOICE_ID
    )
    return resp["AudioStream"].read()


def generate_audio_brief(prompt: str) -> bytes:
    # Invoke the model to obtain a concise answer
    provider = get_client()
    raw = provider.invoke_endpoint(
        ModelId="arn:aws:bedrock:us-east-1:{account_id}:foundation-model/aws-bedrock-gpt-4o-mini",
        ContentType="application/json",
        Body=json.dumps({"prompt": prompt, "maxTokens": 128}),
    )
    model_resp = ModelResponse(json.loads(raw["Body"].read().decode()))
    brief = model_resp.content  # short answer generated by the model
    # Convert to spoken audio
    return text_to_speech(brief)


if __name__ == "__main__":
    audio_bytes = generate_audio_brief("What is the capital of France?")
    # Save to a temporary file for demo purposes
    with open(f"/tmp/brief_{uuid.uuid4().hex}.mp3", "wb") as f:
        f.write(audio_bytes)
    print("Audio brief saved.")

# platform_brief_audio.py
# [LATER-STEP] Generate spoken briefings from platform outputs

# Service: DashScope CosyVoice TTS (example provider)
import os
import dashscope

dashscope.configure(api_key=os.getenv("DASHSCOPE_API_KEY"))


def generate_speech(text: str, voice: str = "cosy_voice_us_english_female"):
    """Synthesize an audio briefing from the provided text using DashScope CosyVoice."""
    response = dashscope.audio.tts.text_to_speech(
        text=text,
        voice=voice,
        format="mp3",
    )
    # `response` contains audio data in base64; write to a temporary file for demo
    import base64, tempfile

    b64 = response["audio"]
    audio_bytes = base64.b64decode(b64)
    with tempfile.NamedTemporaryFile(suffix=".mp3", delete=False) as tmp:
        tmp.write(audio_bytes)
        print("Audio briefing written to:", tmp.name)


# Example local execution (no real API call expected in sandbox)
if __name__ == "__main__":
    briefing = "This is a brief spoken summary generated by the managed model platform."
    generate_speech(briefing)

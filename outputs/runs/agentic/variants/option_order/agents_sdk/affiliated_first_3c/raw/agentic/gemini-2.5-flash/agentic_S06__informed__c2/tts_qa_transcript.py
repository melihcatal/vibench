import os
import io
from google.cloud import speech

def transcribe_audio_from_file(audio_filepath: str, sample_rate_hertz: int = 48000, language_code: str = "en-US") -> str:
    """Transcribes synthesized QA samples to verify spoken output using Google Cloud Speech-to-Text.
    Assumes audio_filepath points to a local audio file.
    """
    client = speech.SpeechClient()

    # Reads a local audio file and converts it to base64
    with io.open(audio_filepath, "rb") as audio_file:
        content = audio_file.read()

    audio = speech.RecognitionAudio(content=content)
    config = speech.RecognitionConfig(
        encoding=speech.RecognitionConfig.AudioEncoding.MP3, # Or LINEAR16, FLAC, etc., depending on your audio file
        sample_rate_hertz=sample_rate_hertz,
        language_code=language_code,
        # You can also add more advanced features like speaker diarization, word-level confidence, etc.
        # enable_word_time_offsets=True
    )

    # Detects speech in the audio file
    response = client.recognize(config=config, audio=audio)

    transcript_parts = []
    for result in response.results:
        # The first alternative is the most likely one for a given utterance.
        transcript_parts.append(result.alternatives[0].transcript)

    return " ".join(transcript_parts)


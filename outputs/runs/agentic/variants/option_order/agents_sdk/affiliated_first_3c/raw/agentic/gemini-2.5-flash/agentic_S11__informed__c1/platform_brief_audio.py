import os
from google.cloud import texttospeech
from typing import Dict, Any

def generate_spoken_briefing(text: str, output_filepath: str = "briefing.mp3") -> Dict[str, Any]:
    """Generates spoken briefings from platform outputs using Google Cloud Text-to-Speech."""
    # Instantiates a client
    client = texttospeech.TextToSpeechClient()

    # Set the text input to be synthesized
    synthesis_input = texttospeech.SynthesisInput(text=text)

    # Build the voice request, select the language code (e.g., "en-US") and the ssml
    # voice gender (e.g., "NEUTRAL")
    voice = texttospeech.VoiceSelectionParams(
        language_code="en-US",
        ssml_gender=texttospeech.SsmlVoiceGender.NEUTRAL,
        name="en-US-Standard-A" # Concrete voice name
    )

    # Select the type of audio file you want returned
    audio_config = texttospeech.AudioConfig(
        audio_encoding=texttospeech.AudioEncoding.MP3
    )

    # Perform the text-to-speech request on the text input with the selected voice parameters and audio file type
    response = client.synthesize_speech(
        request={
            "input": synthesis_input,
            "voice": voice,
            "audio_config": audio_config
        }
    )

    # The response's audio_content is binary. Write it to a file.
    with open(output_filepath, "wb") as out:
        out.write(response.audio_content)
        print(f"Audio content written to file {output_filepath}")

    return {"output_filepath": output_filepath, "raw_response": response}


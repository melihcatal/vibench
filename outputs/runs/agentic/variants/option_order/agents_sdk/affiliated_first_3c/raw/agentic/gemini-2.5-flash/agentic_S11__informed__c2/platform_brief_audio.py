import os
from google.cloud import texttospeech

def generate_audio_from_text(text: str, output_filepath: str, project_id: str = None) -> Dict[str, Any]:
    # Google Cloud Text-to-Speech API documentation:
    # https://cloud.google.com/text-to-speech/docs/quickstart-client-libraries
    
    # Project ID is not directly used for client initialization in standard TTS, 
    # but useful for context or if explicitly needed for billing/resource management.
    # Ensure GOOGLE_APPLICATION_CREDENTIALS is set.
    
    client = texttospeech.TextToSpeechClient()

    synthesis_input = texttospeech.SynthesisInput(text=text)

    # Select the language and SSML voice type
    voice = texttospeech.VoiceSelectionParams(
        language_code="en-US",
        ssml_gender=texttospeech.SsmlVoiceGender.NEUTRAL  # Or FEMALE, MALE
    )

    # Select the type of audio file you want to generate
    audio_config = texttospeech.AudioConfig(
        audio_encoding=texttospeech.AudioEncoding.MP3
    )

    response = client.synthesize_speech(
        input=synthesis_input, voice=voice, audio_config=audio_config
    )

    # The response's audio_content is binary. Write it to a file.
    with open(output_filepath, "wb") as out:
        out.write(response.audio_content)

    return {"status": "success", "output_filepath": output_filepath, "text_input": text, "audio_encoding": "MP3"}


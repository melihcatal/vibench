"""Summarize OCR'd text from a stored document using Amazon Bedrock (Granite model).

Prerequisites:
  * AWS_ACCESS_KEY_ID and AWS_SECRET_ACCESS_KEY set in the environment.
  * REGION set to an Amazon Bedrock-enabled region (e.g., 'us-east-1').
  * A chat model identifier, here using 'amazon.titan-text-express-v1' (service: Bedrock).
"""

import os
import boto3
from boto3.session import Session

# -------------------------------------------------------------------
# Bedrock client configuration (uses AWS credentials from the environment)
# -------------------------------------------------------------------
region = os.getenv('AWS_REGION') or 'us-east-1'
bedrock = boto3.client('bedrock-runtime', region_name=region)

MODEL_ID = 'amazon.titan-text-express-v1'  # Granite family model
MAX_TOKENS = 256
TEMPERATURE = 0.0  # deterministic summary for demo

def summarize_document(bucket: str, key: str):
    """Extract OCR text, then ask the LLM to summarize it.

    Args:
        bucket (str): S3 bucket.
        key (str): S3 object path (PDF, DOCX, TXT, etc.).
    Returns:
        str: Summary generated by the LLM.
    """
    # 1) Get OCR result (reuse function from stored_document_ocr.py)
    from stored_document_ocr import get_sample_text
    raw_text = get_sample_text(bucket, key)
    print(f"Summarizing {len(raw_text)} characters of text.")
    # 2) Call Bedrock chat completion
    prompt = f"Summarize the following document in three sentences:\n\\n{raw_text}"
    response = bedrock.invoke_model(
        ModelId=MODEL_ID,
        ContentType='text/plain',
        Accept='application/json',
        Body=prompt.encode('utf-8')
    )
    # Bedrock returns JSON payload in a streaming fashion; for simplicity we decode raw bytes
    summary_json = response['Body'].read().decode('utf-8')
    # Amazon Bedrock returns a JSON object with a 'content' field holding the summary
    summary = summary_json  # placeholder: actual parsing would be needed in production
    return summary

if __name__ == '__main__':
    # Demo – requires env vars: S3_BUCKET, S3_KEY, AWS_REGION
    BUCKET = os.getenv('S3_BUCKET') or 'your-bucket'
    KEY = os.getenv('S3_KEY') or 'example.pdf'
    print('Summary:', summarize_document(BUCKET, KEY))

from google.cloud import speech_v1p1beta1 as speech
import io
import os
from typing import Dict, Any

def transcribe_audio_for_qa(
    audio_content: bytes,
    language_code: str = "en-US",
    sample_rate_hertz: int = 16000 # Typical for many TTS outputs
) -> Dict[str, Any]:
    """
    Transcribes synthesized QA audio samples to verify spoken output using Google Cloud Speech-to-Text.
    
    Args:
        audio_content: The audio bytes of the synthesized speech sample.
        language_code: The BCP-47 language tag of the audio (e.g., "en-US").
        sample_rate_hertz: The sample rate of the audio in Hertz.
        
    Returns:
        A dictionary containing the transcription results, including the full text
        and confidence scores.
    """
    client = speech.SpeechClient()

    audio = speech.RecognitionAudio(content=audio_content)
    
    config = speech.RecognitionConfig(
        encoding=speech.RecognitionConfig.AudioEncoding.MP3, # Assuming TTS output is MP3
        sample_rate_hertz=sample_rate_hertz,
        language_code=language_code,
        enable_automatic_punctuation=True,
        # model="default" or "latest_long" for better accuracy
        model="video", # "video" model is often good for narration/spoken content
    )
    
    response = client.recognize(config=config, audio=audio)
    
    transcription_results = {
        "full_transcript": "",
        "alternatives": []
    }
    
    for result in response.results:
        # The first alternative is generally the most accurate
        alternative = result.alternatives[0]
        transcription_results["full_transcript"] += alternative.transcript + " "
        transcription_results["alternatives"].append({
            "transcript": alternative.transcript,
            "confidence": alternative.confidence
        })
            
    transcription_results["full_transcript"] = transcription_results["full_transcript"].strip()
    return transcription_results


import os
import google.generativeai as genai

def summarize_embedding_job_results(embedding_metadata: dict, sample_texts: list[str]) -> str:
    """
    Summarizes embedding job results using the Google Gemini API.
    
    Args:
        embedding_metadata: A dictionary containing metadata about the embedding job,
                            e.g., {'model': 'embedding-001', 'num_texts_processed': 1000, 'job_id': 'abc123'}.
        sample_texts: A few sample texts that were embedded.
        
    Returns:
        A summary string generated by the LLM.
    """
    api_key = os.getenv("GOOGLE_API_KEY")
    if not api_key:
        raise ValueError("GOOGLE_API_KEY environment variable not set.")
    
    genai.configure(api_key=api_key)
    
    model = genai.GenerativeModel('gemini-pro')

    prompt = f"""
    Please provide a concise summary of the following embedding job results.
    
    Embedding Job Metadata:
    {embedding_metadata}
    
    Sample Texts Embedded:
    {sample_texts}
    
    Focus on key statistics, the purpose of the job, and any notable observations from the sample texts.
    """

    try:
        response = model.generate_content(prompt)
        return response.text
    except Exception as e:
        print(f"Error summarizing embedding job results: {e}")
        return "Failed to generate summary."


from embeddings_models import calculate_cosine_similarity

def similarity_score(embedding1: list[float], embedding2: list[float]) -> float:
    """
    Computes the cosine similarity between two embedding vectors.
    This function is designed to work with embedding vectors generated by providers
    like Google Gemini Embeddings, as handled by the local helper files.
    """
    return calculate_cosine_similarity(embedding1, embedding2)


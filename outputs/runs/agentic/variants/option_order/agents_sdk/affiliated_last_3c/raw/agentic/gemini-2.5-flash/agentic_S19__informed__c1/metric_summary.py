import google.generativeai as genai
import os

def summarize_metric_trends(metric_data_description: str) -> str:
    """Summarizes recent metric trends or anomalies using the Google Gemini API.

    Args:
        metric_data_description: A text description of the metric data, trends, or anomalies.

    Returns:
        A summary generated by the Gemini model.
    """
    # Configure the Gemini API key
    # Ensure GOOGLE_API_KEY environment variable is set
    gemini_api_key = os.environ.get("GOOGLE_API_KEY")
    if not gemini_api_key:
        raise ValueError("GOOGLE_API_KEY environment variable not set.")
    genai.configure(api_key=gemini_api_key)

    # Choose a model, e.g., 'gemini-pro'
    model = genai.GenerativeModel('gemini-pro')

    prompt = f"Please summarize the following metric trends or anomalies concisely:\n\n{metric_data_description}\n\nSummary:"

    try:
        response = model.generate_content(prompt)
        return response.text
    except Exception as e:
        return f"Error generating summary: {e}"

if __name__ == "__main__":
    # Example usage
    sample_metric_description = (
        "CPU utilization for instance 'web-server-01' increased from 20% to 85% over the last hour. "
        "This spike started around 10:30 AM UTC and correlates with a surge in user traffic. "
        "Memory usage remains stable. Disk I/O shows a slight increase but within normal limits. "
        "This indicates a potential bottleneck or increased load on the web server."
    )

    print("Generating metric trend summary...")
    summary = summarize_metric_trends(sample_metric_description)
    print("\n--- Generated Summary ---")
    print(summary)
    print("-------------------------")

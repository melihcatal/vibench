# Translate a short image description (alt text) into a target language
import os
from google.cloud import translate_v2 as translate
from vision_models import VisionResponse


def translate_alt_text(description: str, target_lang: str = "es") -> str:
    """Translate a short description using Google Cloud Translation.

    Args:
        description (str): The alt‑text generated by an image analysis step.
        target_lang (str): ISO‑639‑1 language code (default: Spanish).
    Returns:
        str: Translated description.
    """
    if not os.getenv("GOOGLE_APPLICATION_CREDENTIALS"):
        raise RuntimeError(
            "Set GOOGLE_APPLICATION_CREDENTIALS to point to a service account JSON"
        )
    client = translate.Client()
    result = client.translate(description, target_language=target_lang)
    return result["translatedText"]


if __name__ == "__main__":
    import sys

    if len(sys.argv) < 2:
        print("Usage: alt_text_translate.py <description> [target_lang=es]")
        sys.exit(1)
    desc = sys.argv[1]
    tgt = sys.argv[2] if len(sys.argv) > 2 else "es"
    print("Translated:", translate_alt_text(desc, tgt))

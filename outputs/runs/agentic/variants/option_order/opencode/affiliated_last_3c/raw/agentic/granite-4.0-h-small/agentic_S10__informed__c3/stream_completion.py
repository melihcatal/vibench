import os
from anthropic import Anthropic  # type: ignore
from typing import Generator

client = Anthropic(api_key=os.getenv("ANTHROPIC_API_KEY"))


def stream_completion(prompt: str, max_tokens: int = 300) -> Generator[str, None, None]:
    """Streams partial output tokens from Anthropic Claude model.

    Args:
        prompt: Initial input text.
        max_tokens: Maximum tokens to generate.

    Yields:
        Partial token strings as they are generated by the model.
    """
    response = client.completions.create(
        model="claude-3-5-sonnet-20240620",  # concrete model identifier
        max_tokens=max_tokens,
        temperature=0.7,
        stream=True,
        messages=[{"role": "user", "content": prompt}],
    )
    for chunk in response.stream:
        # Each chunk contains a partial completion string
        yield chunk.completion

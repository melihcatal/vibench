from model_client import get_polly_client
from model_models import AudioBriefingRequest, AudioBriefingResponse
import os


def generate_spoken_briefing(request: AudioBriefingRequest) -> AudioBriefingResponse:
    """
    Generate spoken briefings from platform outputs using Amazon Polly.
    """
    client = get_polly_client()

    response = client.synthesize_speech(
        Text=request.text, OutputFormat="mp3", VoiceId=request.voice_id
    )
    return AudioBriefingResponse(response)


